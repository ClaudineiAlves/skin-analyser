"""
Módulo de Operações de Imagem para o Pipeline Avançado.

Este arquivo contém a classe ImageOperations, que centraliza todos os métodos
estáticos para manipulação de imagens. Cada método é uma etapa de processamento
autocontida, de conversões básicas a filtros avançados e normalização de cor.
"""

import cv2
import numpy as np
import logging

# --- Tratamento de Dependência Opcional ---
try:
    from skimage import exposure, restoration
    from skimage.color import rgb2hed, hed2rgb
    SKIMAGE_AVAILABLE = True
except ImportError:
    SKIMAGE_AVAILABLE = False
    exposure = restoration = rgb2hed = hed2rgb = None

class ImageOperations:
    """
    Uma classe estática que fornece um kit de ferramentas abrangente de funções de processamento de imagem.
    """

    @staticmethod
    def _to_uint8_bgr(img: np.ndarray) -> np.ndarray:
        # Helper interno para garantir que a imagem esteja no formato BGR uint8.
        if img is None:
            logging.getLogger('ImageOps').error("A imagem de entrada é None.")
            raise ValueError("A imagem de entrada não pode ser None.")
        arr = np.asarray(img)
        if arr.ndim == 2: arr = cv2.cvtColor(arr, cv2.COLOR_GRAY2BGR)
        elif arr.shape[2] == 4: arr = cv2.cvtColor(arr, cv2.COLOR_RGBA2BGR)
        if arr.dtype != np.uint8:
            if np.issubdtype(arr.dtype, np.floating):
                arr = np.clip(arr * 255.0, 0, 255).astype(np.uint8)
            else:
                arr = arr.astype(np.uint8)
        return arr

    # =========================================================================
    # === CATEGORIA 1: LIMPEZA DE ENTRADA
    # =========================================================================

    @staticmethod
    def crop_to_largest_contour(img: np.ndarray, **kwargs) -> np.ndarray:
        # Recorta a imagem para o maior contorno encontrado, útil para remover molduras.
        padding = kwargs.get('padding', 10)
        u8_bgr = ImageOperations._to_uint8_bgr(img)
        gray = cv2.cvtColor(u8_bgr, cv2.COLOR_BGR2GRAY)
        _, thresh = cv2.threshold(gray, 20, 255, cv2.THRESH_BINARY)
        contours, _ = cv2.findContours(thresh, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        if not contours:
            return u8_bgr # Retorna original se nenhum contorno for encontrado
        largest_contour = max(contours, key=cv2.contourArea)
        x, y, w, h = cv2.boundingRect(largest_contour)
        x_pad = max(0, x - padding)
        y_pad = max(0, y - padding)
        w_pad = min(u8_bgr.shape[1], x + w + padding)
        h_pad = min(u8_bgr.shape[0], y + h + padding)
        return u8_bgr[y_pad:h_pad, x_pad:w_pad]

    @staticmethod
    def hair_removal_dullrazor(img: np.ndarray, **kwargs) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        # Implementa o algoritmo DullRazor para remoção de pelos.
        kernel_size = kwargs.get('kernel_size', 15)
        inpaint_radius = kwargs.get('inpaint_radius', 3)
        u8_bgr = ImageOperations._to_uint8_bgr(img)
        gray = cv2.cvtColor(u8_bgr, cv2.COLOR_BGR2GRAY)
        kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (kernel_size, kernel_size))
        blackhat = cv2.morphologyEx(gray, cv2.MORPH_BLACKHAT, kernel)
        _, mask = cv2.threshold(blackhat, 15, 255, cv2.THRESH_BINARY)
        inpainted = cv2.inpaint(u8_bgr, mask, inpaint_radius, cv2.INPAINT_TELEA)
        return inpainted, mask, blackhat

    # =========================================================================
    # === CATEGORIA 2: NORMALIZAÇÃO DE ILUMINAÇÃO E COR
    # =========================================================================

    @staticmethod
    def illumination_shades_of_gray(img: np.ndarray, **kwargs) -> np.ndarray:
        # Algoritmo Shades-of-Gray para normalização de iluminação.
        p_norm = kwargs.get('p_norm', 6)
        u8_bgr = ImageOperations._to_uint8_bgr(img)
        img_float = u8_bgr.astype(np.float32) + 1e-6
        minkowski = lambda ch: np.power(np.mean(np.power(ch, p_norm)), 1/p_norm)
        norms = [minkowski(img_float[:, :, i]) for i in range(3)]
        total_norm = np.power(np.prod(norms), 1/3.0)
        scales = total_norm / norms
        for i in range(3):
            img_float[:, :, i] *= scales[i]
        return np.clip(img_float, 0, 255).astype(np.uint8)

    @staticmethod
    def filter_homomorphic(img: np.ndarray, **kwargs) -> np.ndarray:
        # Filtragem homomórfica para normalizar brilho e aumentar contraste.
        cutoff = kwargs.get('cutoff', 60)
        gamma_h = kwargs.get('gamma_h', 1.5)
        gamma_l = kwargs.get('gamma_l', 0.5)
        u8_gray = cv2.cvtColor(ImageOperations._to_uint8_bgr(img), cv2.COLOR_BGR2GRAY)
        img_log = np.log1p(u8_gray.astype(np.float64))
        img_fft = np.fft.fft2(img_log)
        rows, cols = img_log.shape
        cy, cx = rows // 2, cols // 2
        y, x = np.ogrid[-cy:rows-cy, -cx:cols-cx]
        dist_sq = x*x + y*y
        filter_kernel = (gamma_h - gamma_l) * (1 - np.exp(-dist_sq / (2 * cutoff**2))) + gamma_l
        img_fft_filtered = np.fft.fftshift(img_fft) * filter_kernel
        img_ifft = np.fft.ifft2(np.fft.ifftshift(img_fft_filtered))
        img_exp = np.expm1(np.real(img_ifft))
        return cv2.normalize(img_exp, None, 0, 255, cv2.NORM_MINMAX).astype(np.uint8)

    @staticmethod
    def color_reinhard_normalization(img: np.ndarray, **kwargs) -> np.ndarray:
        # Normalização de cor de Reinhard. CORRIGIDO.
        u8_bgr = ImageOperations._to_uint8_bgr(img)
        img_lab = cv2.cvtColor(u8_bgr, cv2.COLOR_BGR2LAB).astype(np.float32)
        l_mean, l_std = cv2.meanStdDev(img_lab[:, :, 0])
        a_mean, a_std = cv2.meanStdDev(img_lab[:, :, 1])
        b_mean, b_std = cv2.meanStdDev(img_lab[:, :, 2])
        # Espaço de cor de referência (simulando tons de pele médios)
        ref_means = [140.0, 128.0, 140.0]
        ref_stds = [30.0, 5.0, 5.0]
        for i, (mean, std) in enumerate(zip([l_mean, a_mean, b_mean], [l_std, a_std, b_std])):
            img_lab[:, :, i] = ((img_lab[:, :, i] - mean) * (ref_stds[i] / (std[0][0] + 1e-6))) + ref_means[i]
        normalized_lab = np.clip(img_lab, 0, 255).astype(np.uint8)
        return cv2.cvtColor(normalized_lab, cv2.COLOR_LAB2BGR)

    @staticmethod
    def color_macenko_normalization(img: np.ndarray, **kwargs) -> np.ndarray:
        # Normalização de cor de Macenko. CORRIGIDO com blending.
        strength = kwargs.get('strength', 0.6)
        if not SKIMAGE_AVAILABLE:
            logging.getLogger('ImageOps').warning("Scikit-image não encontrado para Macenko. Retornando imagem original.")
            return img
        u8_bgr = ImageOperations._to_uint8_bgr(img)
        img_rgb = cv2.cvtColor(u8_bgr, cv2.COLOR_BGR2RGB)
        img_hed = rgb2hed(img_rgb)
        h = exposure.rescale_intensity(img_hed[:, :, 0], out_range=(0, 1))
        d = exposure.rescale_intensity(img_hed[:, :, 2], out_range=(0, 1))
        zd = np.zeros_like(d)
        norm_rgb = np.clip(hed2rgb(np.dstack((h, zd, d))) * 255, 0, 255).astype(np.uint8)
        norm_bgr = cv2.cvtColor(norm_rgb, cv2.COLOR_RGB2BGR)
        return cv2.addWeighted(u8_bgr, 1 - strength, norm_bgr, strength, 0)

    # =========================================================================
    # === CATEGORIA 3: REDUÇÃO DE RUÍDO
    # =========================================================================

    @staticmethod
    def denoise_median(img: np.ndarray, **kwargs) -> np.ndarray:
        # Filtro de mediana, bom para ruído 'sal e pimenta'.
        kernel_size = kwargs.get('kernel_size', 5)
        k = kernel_size if kernel_size % 2 != 0 else kernel_size + 1
        return cv2.medianBlur(ImageOperations._to_uint8_bgr(img), k)

    @staticmethod
    def denoise_guided(img: np.ndarray, **kwargs) -> np.ndarray:
        # Filtro guiado, excelente para suavizar preservando bordas.
        radius = kwargs.get('radius', 7)
        eps = kwargs.get('eps', 0.02)
        try:
            import cv2.ximgproc
            u8_bgr = ImageOperations._to_uint8_bgr(img)
            return cv2.ximgproc.guidedFilter(u8_bgr, u8_bgr, radius, eps**2)
        except (AttributeError, ImportError):
            logging.getLogger('ImageOps').warning("cv2.ximgproc não encontrado para Filtro Guiado. Usando desfoque gaussiano.")
            return cv2.GaussianBlur(img, (radius, radius) if radius % 2 else (radius+1, radius+1), 0)

    @staticmethod
    def denoise_anisotropic(img: np.ndarray, **kwargs) -> np.ndarray:
        # Anisotropic diffusion using Total Variation denoising.
        if not SKIMAGE_AVAILABLE:
            logging.getLogger('ImageOps').warning("Scikit-image não encontrado para Anisotropic Denoising. Retornando imagem original.")
            return img
        weight = kwargs.get('weight', 0.1)
        img_float = ImageOperations._to_uint8_bgr(img) / 255.0
        denoised_float = restoration.denoise_tv_chambolle(img_float, weight=weight, channel_axis=-1)
        return (denoised_float * 255).astype(np.uint8)

    @staticmethod
    def smooth_kuwahara(img: np.ndarray, **kwargs) -> np.ndarray:
        # Kuwahara-like smoothing using a bilateral filter.
        radius = kwargs.get('radius', 5)
        return cv2.bilateralFilter(ImageOperations._to_uint8_bgr(img), d=radius*2, sigmaColor=75, sigmaSpace=75)

    # =========================================================================
    # === CATEGORIA 4: CONTRAST & INTENSITY ADJUSTMENT
    # =========================================================================

    @staticmethod
    def contrast_clahe(img: np.ndarray, **kwargs) -> np.ndarray:
        # Contrast Limited Adaptive Histogram Equalization.
        clip_limit = kwargs.get('clip_limit', 2.0)
        tile_grid_size = kwargs.get('tile_grid_size', (8, 8))
        u8_bgr = ImageOperations._to_uint8_bgr(img)
        lab = cv2.cvtColor(u8_bgr, cv2.COLOR_BGR2LAB)
        l, a, b = cv2.split(lab)
        clahe = cv2.createCLAHE(clipLimit=clip_limit, tileGridSize=tile_grid_size)
        cl = clahe.apply(l)
        return cv2.cvtColor(cv2.merge((cl, a, b)), cv2.COLOR_LAB2BGR)

    @staticmethod
    def contrast_stretching_linear(img: np.ndarray, **kwargs) -> np.ndarray:
        # Stretches the intensity range of the image to the full 0-255 range.
        return cv2.normalize(ImageOperations._to_uint8_bgr(img), None, 0, 255, cv2.NORM_MINMAX)

    @staticmethod
    def adjust_gamma_power_law(img: np.ndarray, **kwargs) -> np.ndarray:
        # Adjusts image brightness using a power-law (gamma) transformation.
        gamma = kwargs.get('gamma', 1.0)
        u8_bgr = ImageOperations._to_uint8_bgr(img)
        if gamma == 1.0 or gamma <= 0: return u8_bgr
        inv_gamma = 1.0 / gamma
        table = np.array([((i / 255.0) ** inv_gamma) * 255 for i in np.arange(256)]).astype("uint8")
        return cv2.LUT(u8_bgr, table)

    # =========================================================================
    # === CATEGORIA 5: MORPHOLOGICAL PROCESSING
    # =========================================================================

    @staticmethod
    def morphological_opening(img: np.ndarray, **kwargs) -> np.ndarray:
        # Morphological opening (erosion followed by dilation). Removes small bright spots.
        kernel_size = kwargs.get('kernel_size', 3)
        kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (kernel_size, kernel_size))
        return cv2.morphologyEx(ImageOperations._to_uint8_bgr(img), cv2.MORPH_OPEN, kernel)

    @staticmethod
    def morphological_closing(img: np.ndarray, **kwargs) -> np.ndarray:
        # Morphological closing (dilation followed by erosion). Fills small dark holes.
        kernel_size = kwargs.get('kernel_size', 3)
        kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (kernel_size, kernel_size))
        return cv2.morphologyEx(ImageOperations._to_uint8_bgr(img), cv2.MORPH_CLOSE, kernel)

    @staticmethod
    def morphological_black_hat(img: np.ndarray, **kwargs) -> np.ndarray:
        # Highlights dark structures. Returns BGR for compatibility in chains.
        kernel_size = kwargs.get('kernel_size', 21)
        u8_bgr = ImageOperations._to_uint8_bgr(img)
        gray = cv2.cvtColor(u8_bgr, cv2.COLOR_BGR2GRAY)
        kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (kernel_size, kernel_size))
        blackhat = cv2.morphologyEx(gray, cv2.MORPH_BLACKHAT, kernel)
        normalized_blackhat = cv2.normalize(blackhat, None, 0, 255, cv2.NORM_MINMAX)
        return cv2.cvtColor(normalized_blackhat, cv2.COLOR_GRAY2BGR)

    @staticmethod
    def gradient_morphological(img: np.ndarray, **kwargs) -> np.ndarray:
        # Highlights edges using a morphological gradient.
        kernel_size = kwargs.get('kernel_size', 5)
        u8_bgr = ImageOperations._to_uint8_bgr(img)
        gray = cv2.cvtColor(u8_bgr, cv2.COLOR_BGR2GRAY)
        kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (kernel_size, kernel_size))
        gradient = cv2.morphologyEx(gray, cv2.MORPH_GRADIENT, kernel)
        return cv2.cvtColor(gradient, cv2.COLOR_GRAY2BGR)

    # =========================================================================
    # === CATEGORIA 6: EDGE & TEXTURE ENHANCEMENT
    # =========================================================================

    @staticmethod
    def enhance_unsharp_mask(img: np.ndarray, **kwargs) -> np.ndarray:
        # Increases the sharpness of the image.
        amount = kwargs.get('amount', 1.2)
        u8_bgr = ImageOperations._to_uint8_bgr(img)
        blurred = cv2.GaussianBlur(u8_bgr, (0, 0), 5)
        return cv2.addWeighted(u8_bgr, 1.0 + amount, blurred, -amount, 0)

    @staticmethod
    def edge_enhancement_laplacian(img: np.ndarray, **kwargs) -> tuple[np.ndarray, np.ndarray]:
        # Enhances edges by adding a Laplacian filter result back to the original.
        strength = kwargs.get('strength', 0.7)
        u8_bgr = ImageOperations._to_uint8_bgr(img)
        gray = cv2.cvtColor(u8_bgr, cv2.COLOR_BGR2GRAY)
        lap = cv2.Laplacian(gray, cv2.CV_64F)
        lap_u8 = np.clip(np.absolute(lap), 0, 255).astype('uint8')
        lap_colored = cv2.cvtColor(lap_u8, cv2.COLOR_GRAY2BGR)
        return cv2.addWeighted(u8_bgr, 1.0, lap_colored, strength, 0), lap_u8

    @staticmethod
    def edge_sobel(img: np.ndarray, **kwargs) -> np.ndarray:
        # Detects edges using the Sobel operator.
        u8_bgr = ImageOperations._to_uint8_bgr(img)
        gray = cv2.cvtColor(u8_bgr, cv2.COLOR_BGR2GRAY)
        sobelx = cv2.Sobel(gray, cv2.CV_64F, 1, 0, ksize=5)
        sobely = cv2.Sobel(gray, cv2.CV_64F, 0, 1, ksize=5)
        magnitude = np.sqrt(sobelx**2 + sobely**2)
        return cv2.normalize(magnitude, None, 0, 255, cv2.NORM_MINMAX).astype(np.uint8)

    # =========================================================================
    # === CATEGORIA 7: INTENSITY / DOMAIN TRANSFORMATIONS
    # =========================================================================

    @staticmethod
    def transform_log(img: np.ndarray, **kwargs) -> np.ndarray:
        # Applies a logarithmic transformation to expand dark regions.
        img_float = ImageOperations._to_uint8_bgr(img).astype(np.float32) + 1
        log_transformed = np.log(img_float)
        return cv2.normalize(log_transformed, None, 0, 255, cv2.NORM_MINMAX, dtype=cv2.CV_8U)

