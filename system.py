class FlexibleReturn:
    '''
    A reusable dynamic return object for wrapping multiple return values.

    Description:
        This class provides a standard structure for returning multiple values from functions.
        It allows direct indexing, unpacking, and error checking.

    Input:
        *values (any): Arbitrary number of values to wrap.

    Return:
        A FlexibleReturn instance with custom methods for accessing and inspecting wrapped data.
    '''
    def __init__(self, *values):
        self._values = values

    def __iter__(self):
        return iter(self._values)

    def __getitem__(self, index):
        return self._values[index]

    def __len__(self):
        return len(self._values)

    def __repr__(self):
        return repr(self._values[0]) if len(self._values) == 1 else repr(self._values)

    def first(self):
        """
        Returns the first value.

        Return:
            Any: First value or None if empty.
        """
        return self._values[0] if self._values else None

    def all(self):
        """
        Returns all wrapped values as a tuple.

        Return:
            tuple: All stored values.
        """
        return self._values

    def is_empty(self):
        """
        Checks if no values are stored.

        Return:
            bool: True if empty.
        """
        return len(self._values) == 0

    def has_error(self):
        """
        Checks if any wrapped value is an Exception.

        Return:
            bool: True if an error was stored.
        """
        return any(isinstance(v, Exception) for v in self._values)

    def get_error(self):
        """
        Returns the first error if any.

        Return:
            Exception | None: First found Exception or None.
        """
        for v in self._values:
            if isinstance(v, Exception):
                return v
        return None


def wrap_flexible_return(
    log_method: Optional[Union[str, Callable]] = None,
    label: str = "[wrap]",
    raise_on_error: bool = False
):
    def decorator(func):
        @wraps(func)
        def wrapper(*args, **kwargs):
            try:
                result = func(*args, **kwargs)
                return FlexibleReturn(result, True)
            except Exception as e:
                tb = traceback.format_exc()

                logger_func = None
                if callable(log_method):
                    logger_func = log_method
                elif isinstance(log_method, str) and "." in log_method:
                    attr, method = log_method.split(".")
                    instance = getattr(args[0], attr, None)
                    if instance:
                        logger_func = getattr(instance, method, None)

                if logger_func:
                    logger_func(f"{label} Erro capturado em `{func.__name__}`: {str(e)}\n{tb}")
                else:
                    print(f"{label} ERRO: {e}\n{tb}")

                if raise_on_error:
                    raise

                return FlexibleReturn({"value": None, "success": False, "error": str(e), "traceback": tb})
        return wrapper
    return decorator


def silent_fail(log_method=None, label=None):
    """
    Decorator that silently ignores exceptions and optionally logs them.

    Description:
        Use this for non-critical functions where failure is acceptable and should not raise.

    Input:
        log_method (callable): Logger function to report failure (optional).
        label (str): Custom label or identifier for the function in logs.

    Return:
        Function decorator that suppresses exceptions and returns None on failure.
    """
    def decorator(func):
        def wrapper(*args, **kwargs):
            try:
                return func(*args, **kwargs)
            except Exception as e:
                if log_method:
                    log_method(f"{label or func.__name__} failed silently: {e}")
                return None
        return wrapper
    return decorator


