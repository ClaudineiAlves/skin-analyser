def log_call(level="INFO"):
    """
    Decorator to log calls and returns of instance methods.
    Logger is expected to be `self.logger`.
    """
    def decorator(func):
        @wraps(func)
        def wrapper(self, *args, **kwargs):
            logger = getattr(self, "logger", None)
            if logger is None:
                raise AttributeError("Instance has no attribute 'logger'")
            log_method = getattr(logger, level.lower(), logger.info)
            log_method(f"[CALL] {func.__name__} args={args}, kwargs={kwargs}")
            result = func(self, *args, **kwargs)
            log_method(f"[RETURN] {func.__name__} → {result}")
            return result
        return wrapper
    return decorator


def log_process(process_name: str, level: str ="INFO"):
    """
    Decorator to log the start and finish of a process.
    The logger is taken from self.logger at runtime.
    """
    def decorator(func: Callable):
        @wraps(func)
        def wrapper(self, *args, **kwargs) -> Any:
            logger = getattr(self, "logger", None)
            if logger is None:
                raise AttributeError("Instance has no attribute 'logger'")
            log_method = getattr(logger, level.lower(), logger.info)
            log_method(f"[{process_name}] Started")
            try:
                result = func(self, *args, **kwargs)
                log_method(f"[{process_name}] Finished successfully")
                return result
            except Exception as e:
                log_method(f"[{process_name}] Failed with error: {e}")
                raise
        return wrapper
    return decorator
