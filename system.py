import logging
import traceback
import pandas as pd
import numpy as np
import cv2
from pathlib import Path
from typing import List, Dict, Optional, Tuple
from tqdm import tqdm



class DataSetPreprocessor:
    """
    Orchestrates a deterministic, multi-stage image preprocessing pipeline.
    """

    def __init__(self, output_root: str = "./preprocessing_results"):
        # --- Logger Setup ---
        self.logger = logging.getLogger('DataSetPreprocessor')
        if not self.logger.handlers:
            handler = logging.StreamHandler()
            formatter = logging.Formatter('%(asctime)s - %(name)s - %(levelname)s - %(message)s')
            handler.setFormatter(formatter)
            self.logger.addHandler(handler)
        self.logger.setLevel(logging.INFO)

        # --- Path Setup ---
        self.output_root = Path(output_root)
        self.final_outputs_dir = self.output_root / "final_outputs"
        self.support_artifacts_dir = self.output_root / "support_artifacts"
        self.registry_path = self.output_root / "pipeline_registry.csv"
        self._ensure_dir(self.output_root)

        # --- State Variables ---
        self._source_images: List[np.ndarray] = []
        self._source_uids: List[str] = []
        self._source_image_ids: List[int] = []

        # --- Registry Loading ---
        self._registry_df = self._load_registry()

    def _ensure_dir(self, path: Path):
        path.mkdir(parents=True, exist_ok=True)

    def _safe_imwrite(self, path: Path, img: np.ndarray):
        try:
            self._ensure_dir(path.parent)
            if img is None:
                self.logger.warning(f"Attempted to save a null image to {path}. Skipping.")
                return
            if np.issubdtype(img.dtype, np.floating):
                img = np.clip(img, 0, 255).astype(np.uint8)
            if len(img.shape) == 2:
                img = cv2.cvtColor(img, cv2.COLOR_GRAY2BGR)
            cv2.imwrite(str(path), img)
        except Exception as e:
            self.logger.warning(f"Failed to save image to {path}: {e}")

    def _load_registry(self) -> pd.DataFrame:
        if self.registry_path.exists():
            self.logger.info(f"Loading existing registry from {self.registry_path}")
            return pd.read_csv(self.registry_path, dtype={'universal_id': str, 'source_image_id': 'Int64'})
        self.logger.info("No registry found. A new one will be created.")
        return pd.DataFrame(columns=["universal_id", "source_image_id", "variant_name", "file_path", "is_final"])

    def set_images(self, images: List[np.ndarray], universal_ids: List[str], image_ids: List[int]):
        self.logger.info(f"Setting {len(images)} source images for processing.")
        self._source_images = images
        self._source_uids = universal_ids
        self._source_image_ids = image_ids

    def run(self, resume: bool = True) -> Tuple[List[np.ndarray], List[str], List[int], pd.DataFrame]:
        if not self._source_images:
            self.logger.error("No source images have been set. Call set_images() first.")
            return [], [], [], pd.DataFrame()

        self.logger.info(f"=== Starting Preprocessing Pipeline (Resume={resume}) ===")

        # --- ID TRACKING INITIALIZATION ---
        max_id_tracker = {}
        if not self._registry_df.empty:
            numeric_sids = pd.to_numeric(self._registry_df['source_image_id'], errors='coerce')
            max_ids = self._registry_df.assign(source_image_id=numeric_sids).groupby('universal_id')['source_image_id'].max().dropna().astype(int)
            max_id_tracker = max_ids.to_dict()

        new_registry_entries = []
        processed_keys_in_run = set()

        for i in tqdm(range(len(self._source_images)), desc="Processing Source Images"):
            uid, original_sid = self._source_uids[i], self._source_image_ids[i]

            # Use original_sid for caching check
            is_cached = not self._registry_df[(self._registry_df['universal_id'] == uid) & (self._registry_df['source_image_id'] == original_sid)].empty

            if resume and is_cached:
                self.logger.info(f"'{uid}' (Original SID: {original_sid}) found in registry. Skipping processing.")
                continue

            processed_keys_in_run.add(f"{uid}_{original_sid}")

            try:
                last_id = max_id_tracker.get(uid, original_sid - 1)
                if last_id < original_sid - 1: last_id = original_sid - 1

                entries, last_id = self._process_single_image(self._source_images[i], uid, original_sid, last_id)

                max_id_tracker[uid] = last_id
                new_registry_entries.extend(entries)

            except Exception as e:
                self.logger.error(f"Critical error processing '{uid}' (SID: {original_sid}): {e}")
                self.logger.debug(traceback.format_exc())

        if new_registry_entries:
            new_df = pd.DataFrame(new_registry_entries)
            self._registry_df = pd.concat([self._registry_df, new_df], ignore_index=True).drop_duplicates(subset=["universal_id", "source_image_id", "variant_name"], keep='last')
            self._registry_df.to_csv(self.registry_path, index=False)
            self.logger.info(f"Registry updated with {len(new_registry_entries)} new entries.")

        # --- CORRECTED FINAL OUTPUT GATHERING ---
        # Filter the full registry for final images belonging to the UIDs processed in THIS run.
        run_uids = {uid for uid, sid in zip(self._source_uids, self._source_image_ids)}
        final_df = self._registry_df[
            self._registry_df['universal_id'].isin(run_uids) & self._registry_df['is_final']
        ]

        self.logger.info(f"Loading {len(final_df)} final images into memory...")
        final_images, final_uids, final_sids = [], [], []
        if not final_df.empty:
            final_images = [cv2.imread(row['file_path']) for _, row in final_df.iterrows()]
            valid_indices = [i for i, img in enumerate(final_images) if img is not None]

            final_images = [final_images[i] for i in valid_indices]
            final_df_filtered = final_df.iloc[valid_indices]
            final_uids = final_df_filtered['universal_id'].tolist()
            final_sids = final_df_filtered['source_image_id'].tolist()
        else:
            final_df_filtered = pd.DataFrame()

        self.logger.info("=== Pipeline Completed Successfully ===")
        return final_images, final_uids, final_sids, final_df_filtered.copy()

    def _process_single_image(self, img: np.ndarray, uid: str, original_sid: int, last_id: int) -> Tuple[List[Dict], int]:
        variants = {}
        metadata = []
        current_id_counter = last_id

        def execute_and_save(op_name: str, input_img: np.ndarray, context: str = "") -> Optional[np.ndarray]:
            folder_name = context if context else op_name
            support_dir = self.support_artifacts_dir / "execution_steps" / uid / str(original_sid) / folder_name
            self._safe_imwrite(support_dir / "before_modifier.png", input_img)
            try:
                operation = getattr(ImageOperations, op_name)
                params = DEFAULT_PARAMS.get(op_name, {})
                result = operation(input_img, **params)
                main_output, support_outputs = (result[0], result[1:]) if isinstance(result, tuple) else (result, [])
                self._safe_imwrite(support_dir / "after_modifier.png", main_output)
                for i, sup_img in enumerate(support_outputs):
                    self._safe_imwrite(support_dir / f"support_output_{i+1}.png", sup_img)
                return main_output
            except Exception as e:
                self.logger.error(f"  - FAILED on operation '{folder_name}' (op: {op_name}): {e}")
                return None

        def _register_variant(variant_name: str, image_data: np.ndarray):
            nonlocal current_id_counter
            if image_data is None: return

            # Your original logic to determine if an output is final
            is_final = variant_name not in ['original_rgb', 'initial_crop']

            # Assign new ID for every variant
            current_id_counter += 1
            new_sid = current_id_counter

            if is_final:
                f_path = self.final_outputs_dir / variant_name / f"{uid}_{new_sid}.png"
            else:
                f_path = self.support_artifacts_dir / "intermediate_stages" / variant_name / f"{uid}_{new_sid}.png"

            self._safe_imwrite(f_path, image_data)

            metadata.append({
                "universal_id": uid, "source_image_id": new_sid,
                "variant_name": variant_name, "file_path": str(f_path.resolve()),
                "is_final": is_final
            })
            variants[variant_name] = image_data

        # Register the original image variant itself with its original SID
        variants['original_rgb'] = img
        metadata.append({
            "universal_id": uid, "source_image_id": original_sid,
            "variant_name": 'original_rgb', "file_path": 'N/A - In Memory',
            "is_final": False
        })

        # Run pipeline stages
        for stage in PIPELINE_STAGES:
            op, src, out = stage['op'], stage['source'], stage['output']
            if src not in variants:
                self.logger.warning(f"Source '{src}' not found for stage '{out}'. Skipping.")
                continue
            result_img = execute_and_save(op, variants[src], context=out)
            _register_variant(out, result_img)

        # Run combined chains
        for chain_name, steps in COMBINED_OUTPUT_CHAINS.items():
            current_image = None
            for i, step in enumerate(steps):
                op = step['op']
                if i == 0:
                    src = step.get('source', 'hair_removed')
                    if src not in variants:
                        self.logger.error(f"Source '{src}' for chain '{chain_name}' not found. Aborting chain.")
                        current_image = None; break
                    current_image = variants[src]
                if current_image is not None:
                    context = f"{chain_name}_step{i+1}_{op}"
                    current_image = execute_and_save(op, current_image, context=context)
            if current_image is not None:
                _register_variant(chain_name, current_image)

        return metadata, current_id_counter

