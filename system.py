class ConfigReaderIntegration:
    """
    ConfigReaderIntegration

    A class to load, read, update, and save JSON configuration files using structured categories and subtypes.
    """

    def __init__(self, filepath: str, category: str):
        """
        Description:
            Initializes the configuration reader for a given file and category.

        Parameters:
            filepath (str): Path to the JSON configuration file.
            category (str): Root key in the JSON under which subtypes and values are stored.

        Returns:
            None
        """
        self._file_path = Path(filepath)
        self._category = category
        self._config_data = None
        self._initialization()

    def _initialization(self):
        """
        Description:
            Loads the JSON file into memory.

        Parameters:
            None

        Returns:
            None

        Exceptions:
            Prints an error if file is missing or contains invalid JSON.
        """
        try:
            with open(self._file_path, 'r', encoding='utf-8') as f:
                self._config_data = json.load(f)
        except FileNotFoundError as e:
            print(f"[ERROR] File not found: {e}")
            raise FileNotFoundError(f"File not found: {e}")
        except json.JSONDecodeError as e:
            print(f"[ERROR] Invalid JSON format: {e}")
            raise ValueError(f"Invalid JSON: {e}")

    def reload(self):
        """
        Description:
            Reloads the configuration file from disk.

        Parameters:
            None

        Returns:
            None
        """
        self._initialization()

    def getConfigBySubtype(self, subtype, default=None):
        """
        Description:
            Retrieves a configuration block (subtype) under the current category.

        Parameters:
            subtype (str): Sub-key under the current category to retrieve.
            default (Any, optional): Default value to return if not found. Defaults to None.

        Returns:
            dict | Any: Subtype config dictionary or default value.
        """
        if self._config_data is None:
            print("[ERROR] Configuration not loaded.")
            raise Exception("Configuration not loaded.")
        return self._config_data.get(self._category, {}).get(subtype, default)

    def listSubtypes(self):
        """
        Description:
            Lists all available subtypes under the current category.

        Parameters:
            None

        Returns:
            list[str]: List of subtype names.
        """
        return list(self._config_data.get(self._category, {}).keys())

    def getNested(self, subtype, *path, default=None):
        """
        Description:
            Retrieves a nested configuration value inside a subtype using a path.

        Parameters:
            subtype (str): Name of the configuration subtype.
            *path (str): Sequence of keys representing the path to the nested value.
            default (Any, optional): Value to return if path does not exist. Defaults to None.

        Returns:
            Any: The value at the specified path, or the default value.
        """
        config = self.getConfigBySubtype(subtype)
        for key in path:
            if isinstance(config, dict):
                config = config.get(key, default)
            else:
                return default
        return config

    @property
    def config(self):
        """
        Description:
            Returns the full configuration data loaded from the file.

        Parameters:
            None

        Returns:
            dict | None: Full config dictionary or None if not loaded.
        """
        return self._config_data

    def setConfigValue(self, subtype, key_path, value):
        """
        Description:
            Sets or updates a nested configuration value for a specific subtype.

        Parameters:
            subtype (str): The name of the subtype to update.
            key_path (list[str]): List of nested keys to traverse.
            value (Any): The value to assign at the final key.

        Returns:
            None

        Exceptions:
            Prints an error if config is not loaded.
        """
        if self._config_data is None:
            print("[ERROR] Configuration not loaded.")
            raise Exception("Configuration not loaded.")

        if self._category not in self._config_data:
            self._config_data[self._category] = {}

        if subtype not in self._config_data[self._category]:
            self._config_data[self._category][subtype] = {}

        ref = self._config_data[self._category][subtype]
        for key in key_path[:-1]:
            if key not in ref or not isinstance(ref[key], dict):
                ref[key] = {}
            ref = ref[key]

        ref[key_path[-1]] = value

    def save(self):
        """
        Description:
            Saves the current configuration data back to the JSON file.

        Parameters:
            None

        Returns:
            None

        Exceptions:
            Prints an error if saving fails.
        """
        try:
            with open(self._file_path, "w", encoding="utf-8") as f:
                json.dump(self._config_data, f, indent=4, ensure_ascii=False)
        except Exception as e:
            print(f"[ERROR] Failed to save configuration: {e}")
            raise
