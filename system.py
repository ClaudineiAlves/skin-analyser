def full_wrap(logger_attr="logger", flex_label="[flex-return]", raise_on_error=False):
    def decorator(func):
        @wraps(func)
        def wrapper(*args, **kwargs):
            instance = args[0]
            logger = getattr(instance, logger_attr, None)
            if logger is None:
                raise AttributeError(f"Logger '{logger_attr}' not found in {instance}")
            wrapped = log_call()(func)
            wrapped = wrap_flexible_return(log_method=logger.error, label=flex_label, raise_on_error=raise_on_error)(wrapped)
            return wrapped(*args, **kwargs)
        return wrapper
    return decorator

