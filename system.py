    def getData(self,
            table: str,
            filters: dict = None,
            enabledlimite: bool = None,
            limit: int = None,
            enabledrange: bool = None,
            range_values: tuple = None
        ):
        '''
        Retrieves data from the specified table with optional filters and range.

        Args:
            table (str): Name of the Supabase table.
            filters (dict): Optional query filters.
            limit (int): Optional max limit.
            range_values (tuple): Optional (from, to) index range.

        Returns:
            PostgrestResponse: Supabase API response.
        '''
        try:
            if not table:
                self.logger.error("Table name is not configured.")
                raise ValueError("Table name is not configured.")

            if not self._Cliente:
                self.connect()

            query = self._Cliente.table(table).select("*")

            # Apply filters to the query
            if filters:
                for key, condition in filters.items():
                    if isinstance(condition, dict):
                        for op, value in condition.items():
                            if op == 'gte': query = query.gte(key, value)
                            elif op == 'lte': query = query.lte(key, value)
                            elif op == 'gt': query = query.gt(key, value)
                            elif op == 'lt': query = query.lt(key, value)
                            elif op == 'eq': query = query.eq(key, value)
                            elif op == 'neq': query = query.neq(key, value)
                            elif op == 'like': query = query.like(key, value)
                            elif op == 'ilike': query = query.ilike(key, value)
                            elif op == 'is': query = query.is_(key, value)
                            elif op == 'isnot': query = query.isnot(key, value)
                            elif op == 'in': query = query.in_(key, value)
                            elif op == 'not_in': query = query.not_in(key, value)
                            elif op == 'contains': query = query.contains(key, value)
                    else:
                        query = query.eq(key, condition)

            # Apply limit if provided or from config
            if enabledlimite is None:
                enabledlimite = self._toggle_limit
            if enabledlimite:
                reqlimit = limit if limit is not None else self._max_req_limit
                if reqlimit is not None:
                    query = query.limit(reqlimit)

            # Apply range if provided or from config
            if enabledrange is None:
                enabledrange = self._toggle_range
            if enabledrange:
                range_from = range_values[0] if range_values else self._range_from
                range_to = range_values[1] if range_values else self._range_to
                if range_from is not None and range_to is not None:
                    query = query.range(range_from, range_to)

            self._consoleTools.log_request(
                method="GET",
                endpoint=f"/{table}",
                payload=None,
                headers=None
            )

            with self._consoleTools.show_progress(total=5, description="Authentication to Supabase..."):
                time.sleep(0.50)
                response = query.execute()

            if response.data is None:
                self.logger.error(f"Error fetching data: {response}")
                self._consoleTools.log_response(
                    status_code=500,
                    data={
                        "message": "Error fetching data",
                        "content": str(response)
                    },
                    elapsed=0.5
                )
            else:
                self.logger.info(f"Data retrieved: {len(response.data)} rows.")
                self._consoleTools.log_response(
                    status_code=200,
                    data={
                        "message": "Data retrieved",
                        "content": str(response)
                    },
                    elapsed=0.5
                )

            if self._toggle_auto_save == True:
                self.saveDataDF(response.data, table)

            return response
        except Exception as e:
            self.logger.critical(f"Error in get data: {e}")
            self._consoleTools.log_response(
                status_code=500,
                data={
                    "message": "Error in get data",
                    "content": str(e)
                },
                elapsed=0.5
            )
            return None



    def saveDataDF(
        self,
        data,  # Can be a DataFrame or a list of dictionaries
        table_name: str,
        file_path: str = None
    ):
        '''Coment:
        Saves tabular data (DataFrame or list of dictionaries) to a CSV file.

        Args:
            data: The data to be saved. It can be a pandas DataFrame or a list of dictionaries.
            table (str): The table name used as default filename.
            filepath (str, optional): Directory path to save the file. Uses internal config if not provided.
            filename (str, optional): File name without extension. Defaults to the table name.
        '''
        if data is None or table_name is None:
            self.logger.warning("No data or table name provided. Skipping save operation.")
            return

        # Ensure the data is a DataFrame
        if not isinstance(data, pd.DataFrame):
            try:
                data = pd.DataFrame(data)
            except Exception as e:
                self.logger.error(f"Failed to convert data to DataFrame: {e}")
                return

        # Define save path and filename
        filepath = file_path or self._save_file_dir
        filename = table_name
        full_path = os.path.join(filepath, f"{filename}.csv")

        # Create the directory if it doesn't exist
        os.makedirs(filepath, exist_ok=True)

        try:
            data.to_csv(full_path, index=False)
            self.logger.info(f"Data from table '{table_name}' successfully saved to: {full_path}")

        except Exception as e:
            self.logger.critical(f"Failed to save CSV file: {e}")

