    def progress_bar(self, total: int, description: str = "Processing"):
        '''
            Description:
                Create a progress bar.
            Parameters:
                total (int): Total number of steps.
                description (str): Description for the progress bar.
            return:
                tuple: (Progress, TaskID)
        '''
        progress = Progress()
        task_id = progress.add_task(description, total=total)
        return progress, task_id

    @contextmanager
    def show_progress(self, total: int, description: str = "Processing", delay: float = 0.5):
        """
        Context manager para exibir uma barra de progresso durante uma operação.

        Args:
            total (int): Total de etapas do progresso.
            description (str): Texto descritivo na barra.
            delay (float): Intervalo entre cada avanço automático da barra.
        """
        progress = Progress()
        task_id = progress.add_task(description, total=total)

        def update_bar():
            while not progress.finished:
                progress.update(task_id, advance=1)
                time.sleep(delay)

        thread = threading.Thread(target=update_bar, daemon=True)

        try:
            progress.start()
            thread.start()
            yield  # executa o bloco de código dentro do with
        finally:
            progress.update(task_id, completed=total)
            progress.stop()
            thread.join()
