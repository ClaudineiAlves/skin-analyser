def now_utc_str() -> str:
    """Returns the current UTC timestamp as a formatted string."""
    return datetime.now(timezone.utc).strftime('%Y%m%d%H%M%S%f')

def ensure_dir(path: Path):
    """Ensures a directory exists, creating it if necessary."""
    path.mkdir(parents=True, exist_ok=True)

def safe_imwrite_pil(path: Path, img: Image.Image) -> bool:
    """Safely saves a Pillow Image to disk."""
    try:
        ensure_dir(path.parent)
        if img.mode != 'RGB':
            img = img.convert('RGB')
        img.save(path, format='PNG')
        return True
    except Exception as e:
        logging.getLogger('ExponentialAugmentor').error(f"Failed to save image to {path}: {e}")
        return False

def to_pil(arr: np.ndarray) -> Image.Image:
    """Converts a NumPy array (assumed BGR) to a Pillow Image (RGB)."""
    if arr.ndim == 3 and arr.shape[2] == 3:
        return Image.fromarray(cv2.cvtColor(arr, cv2.COLOR_BGR2RGB))
    elif arr.ndim == 2:
        return Image.fromarray(arr, 'L')
    raise ValueError(f"Unsupported array shape for PIL conversion: {arr.shape}")

def from_pil(img: Image.Image) -> np.ndarray:
    """Converts a Pillow Image (assumed RGB) to a NumPy array (BGR)."""
    return cv2.cvtColor(np.array(img.convert('RGB')), cv2.COLOR_RGB2BGR)


class AugmentationOps:
    """A static class containing an expanded suite of image augmentation methods."""

    # === 1. Geometric Transformations ===
    @staticmethod
    def rotation(img: Image.Image, angles: List[float]) -> List[Tuple[Image.Image, Dict]]:
        return [(img.rotate(angle, resample=Image.BICUBIC, expand=False), {'angle': angle}) for angle in angles]

    @staticmethod
    def flip(img: Image.Image, flip_types: List[str]) -> List[Tuple[Image.Image, Dict]]:
        results = []
        if 'horizontal' in flip_types:
            results.append((img.transpose(Image.FLIP_LEFT_RIGHT), {'flip': 'horizontal'}))
        if 'vertical' in flip_types:
            results.append((img.transpose(Image.FLIP_TOP_BOTTOM), {'flip': 'vertical'}))
        return results

    @staticmethod
    def crop(img: Image.Image, crop_percentages: List[float]) -> List[Tuple[Image.Image, Dict]]:
        w, h = img.size
        results = []
        for p in crop_percentages:
            new_w, new_h = int(w * p), int(h * p)
            if w > new_w and h > new_h:
                left, top = random.randint(0, w - new_w), random.randint(0, h - new_h)
                cropped = img.crop((left, top, left + new_w, top + new_h))
                resized = cropped.resize((w, h), resample=Image.BICUBIC)
                results.append((resized, {'crop_percentage': p, 'from_x': left, 'from_y': top}))
        return results

    @staticmethod
    def translation(img: Image.Image, trans_factors: List[float]) -> List[Tuple[Image.Image, Dict]]:
        w, h = img.size
        results = []
        for f in trans_factors:
            dx, dy = int(w * f * (random.random() - 0.5)), int(h * f * (random.random() - 0.5))
            translated = img.transform(img.size, Image.AFFINE, (1, 0, dx, 0, 1, dy))
            results.append((translated, {'trans_x': dx, 'trans_y': dy}))
        return results

    @staticmethod
    def zoom(img: Image.Image, factors: List[float]) -> List[Tuple[Image.Image, Dict]]:
        w, h = img.size
        results = []
        for z in factors:
            if z > 1.0:
                crop_w, crop_h = int(w / z), int(h / z)
                if w > crop_w and h > crop_h:
                    left, top = (w - crop_w) // 2, (h - crop_h) // 2
                    zoomed = img.crop((left, top, left + crop_w, top + crop_h)).resize((w, h), resample=Image.BICUBIC)
                    results.append((zoomed, {'zoom_factor': z}))
            else:
                new_w, new_h = int(w * z), int(h * z)
                shrunk = img.resize((new_w, new_h), resample=Image.BICUBIC)
                zoomed = Image.new(img.mode, (w, h), (0,0,0))
                zoomed.paste(shrunk, ((w - new_w) // 2, (h - new_h) // 2))
                results.append((zoomed, {'zoom_factor': z}))
        return results

    @staticmethod
    def shear(img: Image.Image, angles: List[float]) -> List[Tuple[Image.Image, Dict]]:
        results = []
        for angle in angles:
            shear_factor = np.tan(np.radians(angle))
            sheared = img.transform(img.size, Image.AFFINE, (1, shear_factor, 0, 0, 1, 0))
            results.append((sheared, {'shear_angle': angle}))
        return results

    @staticmethod
    def perspective(img: Image.Image, magnitudes: List[float]) -> List[Tuple[Image.Image, Dict]]:
        img_cv = from_pil(img)
        h, w = img_cv.shape[:2]
        results = []
        for m in magnitudes:
            src_points = np.float32([[0, 0], [w - 1, 0], [0, h - 1], [w - 1, h - 1]])
            dw, dh = w * m, h * m
            dst_points = np.float32([
                [random.uniform(-dw, dw), random.uniform(-dh, dh)],
                [w - 1 + random.uniform(-dw, dw), random.uniform(-dh, dh)],
                [random.uniform(-dw, dw), h - 1 + random.uniform(-dh, dh)],
                [w - 1 + random.uniform(-dw, dw), h - 1 + random.uniform(-dh, dh)]
            ])
            M = cv2.getPerspectiveTransform(src_points, dst_points)
            warped_cv = cv2.warpPerspective(img_cv, M, (w, h))
            results.append((to_pil(warped_cv), {'perspective_magnitude': m}))
        return results

    @staticmethod
    def elastic(img: Image.Image, alpha: List[float], sigma: List[float]) -> List[Tuple[Image.Image, Dict]]:
        if gaussian_filter is None: return []
        results = []
        img_np_rgb = np.array(img.convert('RGB'))
        shape = img_np_rgb.shape[:2]
        for a in alpha:
            for s in sigma:
                dx = gaussian_filter((np.random.rand(*shape) * 2 - 1), s, mode="constant", cval=0) * a
                dy = gaussian_filter((np.random.rand(*shape) * 2 - 1), s, mode="constant", cval=0) * a
                x, y = np.meshgrid(np.arange(shape[1]), np.arange(shape[0]))
                indices = np.reshape(y + dy, (-1, 1)), np.reshape(x + dx, (-1, 1))
                deformed_channels = [map_coordinates(img_np_rgb[..., i], indices, order=1, mode="reflect").reshape(shape) for i in range(img_np_rgb.shape[2])]
                deformed_img_np = np.stack(deformed_channels, axis=-1).astype(np.uint8)
                results.append((Image.fromarray(deformed_img_np), {'elastic_alpha': a, 'elastic_sigma': s}))
        return results

    # === 2. Color & Lighting Transformations ===
    @staticmethod
    def color_jitter(img: Image.Image, brightness: List[float], contrast: List[float], saturation: List[float], hue: List[float]) -> List[Tuple[Image.Image, Dict]]:
        results = []
        for b in brightness:
            for c in contrast:
                for s in saturation:
                    for h_factor in hue:
                        temp_img = ImageEnhance.Brightness(img).enhance(b)
                        temp_img = ImageEnhance.Contrast(temp_img).enhance(c)
                        temp_img = ImageEnhance.Color(temp_img).enhance(s)
                        if h_factor != 0:
                            img_hsv = np.array(temp_img.convert('HSV'))
                            hue_channel = img_hsv[..., 0].astype(np.int16)
                            hue_channel = (hue_channel + int(255 * h_factor)) % 256
                            img_hsv[..., 0] = hue_channel.astype(np.uint8)
                            temp_img = Image.fromarray(img_hsv, 'HSV').convert('RGB')
                        results.append((temp_img, {'brightness': b, 'contrast': c, 'saturation': s, 'hue': h_factor}))
        return results

    @staticmethod
    def gamma_correction(img: Image.Image, gammas: List[float]) -> List[Tuple[Image.Image, Dict]]:
        results = []
        for gamma in gammas:
            inv_gamma = 1.0 / gamma
            table = np.array([((i / 255.0) ** inv_gamma) * 255 for i in np.arange(0, 256)]).astype("uint8")
            gamma_img = to_pil(cv2.LUT(from_pil(img), table))
            results.append((gamma_img, {'gamma': gamma}))
        return results

    @staticmethod
    def histogram_equalization(img: Image.Image, strengths: List[float]) -> List[Tuple[Image.Image, Dict]]:
        results = []
        equalized = ImageOps.equalize(img)
        for s in strengths:
            blended = Image.blend(img, equalized, s)
            results.append((blended, {'hist_eq_strength': s}))
        return results

    @staticmethod
    def channel_shuffle(img: Image.Image, **kwargs) -> List[Tuple[Image.Image, Dict]]:
        r, g, b = img.split()
        shuffled = Image.merge("RGB", (b, g, r))
        return [(shuffled, {'shuffle_type': 'bgr'})]

    @staticmethod
    def invert(img: Image.Image, **kwargs) -> List[Tuple[Image.Image, Dict]]:
        return [(ImageOps.invert(img.convert('RGB')), {})]

    @staticmethod
    def solarize(img: Image.Image, thresholds: List[int]) -> List[Tuple[Image.Image, Dict]]:
        return [(ImageOps.solarize(img, threshold=t), {'solarize_threshold': t}) for t in thresholds]

    @staticmethod
    def posterize(img: Image.Image, bits_list: List[int]) -> List[Tuple[Image.Image, Dict]]:
        return [(ImageOps.posterize(img, bits=b), {'posterize_bits': b}) for b in bits_list]

    # === 3. Noise, Blur & Perturbations ===
    @staticmethod
    def noise(img: Image.Image, std_devs: List[float], salt_pepper_amounts: List[float], speckle_strengths: List[float]) -> List[Tuple[Image.Image, Dict]]:
        results = []
        img_np = np.array(img.convert('RGB')).astype(np.float32)
        for std in std_devs:
            noise = np.random.normal(0, std, img_np.shape)
            noisy_img = np.clip(img_np + noise, 0, 255).astype(np.uint8)
            results.append((Image.fromarray(noisy_img), {'noise_type': 'gaussian', 'std_dev': std}))
        for amount in salt_pepper_amounts:
            noisy_img = np.copy(img_np)
            num_salt = np.ceil(amount * img_np.size * 0.5)
            coords = [np.random.randint(0, i - 1, int(num_salt)) for i in img_np.shape]
            if coords[0].size > 0: noisy_img[coords[0], coords[1], :] = 255
            num_pepper = np.ceil(amount * img_np.size * 0.5)
            coords = [np.random.randint(0, i - 1, int(num_pepper)) for i in img_np.shape]
            if coords[0].size > 0: noisy_img[coords[0], coords[1], :] = 0
            results.append((Image.fromarray(noisy_img.astype(np.uint8)), {'noise_type': 'salt_pepper', 'amount': amount}))
        for strength in speckle_strengths:
            noise = np.random.randn(*img_np.shape) * strength
            noisy_img = np.clip(img_np + img_np * noise, 0, 255).astype(np.uint8)
            results.append((Image.fromarray(noisy_img), {'noise_type': 'speckle', 'strength': strength}))
        return results

    @staticmethod
    def blur(img: Image.Image, radius: List[float], motion_blur_kernels: List[int]) -> List[Tuple[Image.Image, Dict]]:
        results = []
        for rad in radius:
            results.append((img.filter(ImageFilter.GaussianBlur(rad)), {'blur_type': 'gaussian', 'radius': rad}))
        img_cv = from_pil(img)
        for k_size in motion_blur_kernels:
            kernel = np.zeros((k_size, k_size))
            kernel[int((k_size-1)/2), :] = np.ones(k_size)
            kernel = kernel / k_size
            motion_blurred = cv2.filter2D(img_cv, -1, kernel)
            results.append((to_pil(motion_blurred), {'blur_type': 'motion', 'kernel_size': k_size}))
        return results

    @staticmethod
    def sharpen(img: Image.Image, factors: List[float]) -> List[Tuple[Image.Image, Dict]]:
        return [(ImageEnhance.Sharpness(img).enhance(factor), {'sharpen_factor': factor}) for factor in factors]

    @staticmethod
    def jpeg_compression(img: Image.Image, qualities: List[int]) -> List[Tuple[Image.Image, Dict]]:
        results = []
        for q in qualities:
            buffer = io.BytesIO()
            img.save(buffer, "JPEG", quality=q)
            buffer.seek(0)
            compressed_img = Image.open(buffer)
            compressed_img.load()
            results.append((compressed_img.convert('RGB'), {'jpeg_quality': q}))
        return results

    @staticmethod
    def cutout(img: Image.Image, num_holes: List[int], max_size_factors: List[float], fill_values: list) -> List[Tuple[Image.Image, Dict]]:
        results = []
        img_np = from_pil(img)
        h, w = img_np.shape[:2]
        for n in num_holes:
            for size_factor in max_size_factors:
                for fill in fill_values:
                    cutout_img = np.copy(img_np)
                    if fill == 'random':
                        fill_value = random.randint(0, 255)
                    else:
                        fill_value = int(fill)
                    hole_h, hole_w = int(h * size_factor), int(w * size_factor)
                    for _ in range(n):
                        if h > hole_h and w > hole_w:
                            y1 = np.random.randint(0, h - hole_h)
                            x1 = np.random.randint(0, w - hole_w)
                            y2, x2 = y1 + hole_h, x1 + hole_w
                            cutout_img[y1:y2, x1:x2] = fill_value
                    results.append((to_pil(cutout_img), {'cutout_holes': n, 'size': size_factor, 'fill': fill}))
        return results

