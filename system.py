class DataOrganizer:
    """
    Organizes a processed DataFrame into separate lists for specified columns,
    ensuring perfect alignment with a given list of IDs.
    """
    def __init__(self, dataframe: pd.DataFrame, ids: List[str], primary_key: str = 'universal_id'):
        """
        Initializes the organizer.

        Args:
            dataframe (pd.DataFrame): The processed and encoded DataFrame.
            ids (List[str]): The definitive list of IDs to align with.
            primary_key (str): The name of the primary key column in the DataFrame.
        """
        logger.info("Initializing DataOrganizer.")
        try:
            if primary_key not in dataframe.columns:
                raise ValueError(f"Primary key '{primary_key}' not found in the DataFrame.")
            if not isinstance(ids, list):
                raise TypeError("The 'ids' parameter must be a list.")

            logger.info(f"Aligning DataFrame with {len(ids)} provided IDs.")
            # Reindex the DataFrame to match the exact order and content of the `ids` list.
            self.df_aligned = dataframe.set_index(primary_key).reindex(ids).reset_index()

            if self.df_aligned.isnull().values.any():
                missing_ids_count = self.df_aligned.isnull().any(axis=1).sum()
                logger.warning(f"{missing_ids_count} IDs from the list were not found in the DataFrame, resulting in NaN rows.")

        except (ValueError, TypeError) as e:
            logger.error(f"Error during DataOrganizer initialization: {e}")
            raise

    def get_column_lists(self, columns_to_extract: List[str]) -> Dict[str, List[Any]]:
        """
        Extracts specified columns from the aligned DataFrame into a dictionary of lists.

        Args:
            columns_to_extract (List[str]): A list of column names to extract.

        Returns:
            Dict[str, List[Any]]: A dictionary where keys are column names and
                                  values are the corresponding data as lists.
        """
        logger.info(f"Extracting columns into separate lists: {columns_to_extract}")
        organized_data = {}
        for col in columns_to_extract:
            if col not in self.df_aligned.columns:
                logger.warning(f"Column '{col}' not found in the DataFrame. Skipping.")
                continue
            organized_data[col] = self.df_aligned[col].tolist()
            logger.info(f"  - Extracted '{col}' successfully ({len(organized_data[col])} items).")
        return organized_data

