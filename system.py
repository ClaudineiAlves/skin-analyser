# --- CALLBACK PERSONALIZADO PARA SALVAR HISTÓRICO ---
class SaveHistoryToCSV(Callback):
    """Callback que guarda o histórico de treino num ficheiro CSV."""
    def __init__(self, filepath):
        super(SaveHistoryToCSV, self).__init__()
        self.filepath = filepath
        self.history_data = []

    def on_epoch_end(self, epoch, logs=None):
        # O 'logs' é um dicionário com as métricas da época atual (loss, acc, val_loss, etc.)
        # Adiciona o número da época para referência
        logs_copy = logs.copy()
        logs_copy['epoch'] = epoch + 1
        self.history_data.append(logs_copy)

    def on_train_end(self, logs=None):
        # Quando o treino termina, converte a lista de dicionários para um DataFrame
        history_df = pd.DataFrame(self.history_data)
        # Salva o DataFrame num ficheiro CSV
        history_df.to_csv(self.filepath, index=False)
        TLogger.info(f"Histórico de treino salvo com sucesso em: {self.filepath}")


# --- FUNÇÃO PRINCIPAL PARA OBTER OS CALLBACKS ---
def get_training_callbacks(model_save_path, history_save_path):
    """
    Cria e retorna uma lista com os callbacks recomendados para o treino.

    Args:
        model_save_path (str): Caminho para salvar o melhor modelo.
        history_save_path (str): Caminho para salvar o histórico do treino em CSV.

    Returns:
        list: Uma lista de callbacks do Keras prontos para usar no model.fit().
    """
    TLogger.info("A configurar os callbacks de treino...")

    # 1. ModelCheckpoint: Guarda apenas o melhor modelo com base na perda de validação.
    checkpoint_callback = ModelCheckpoint(
        filepath=model_save_path,
        monitor='val_loss',
        save_best_only=True,
        verbose=1
    )

    # 2. EarlyStopping: Para o treino se a perda de validação não melhorar em 5 épocas.
    early_stopping_callback = EarlyStopping(
        monitor='val_loss',
        patience=5,
        restore_best_weights=True, # Restaura os pesos do melhor modelo no final
        verbose=1
    )

    # 3. ReduceLROnPlateau: Reduz a taxa de aprendizagem se a perda de validação estagnar.
    reduce_lr_callback = ReduceLROnPlateau(
        monitor='val_loss',
        factor=0.2, # Reduz a LR para 20% do valor atual
        patience=3,
        min_lr=1e-6, # Taxa de aprendizagem mínima
        verbose=1
    )

    # 4. Callback personalizado para salvar o histórico em CSV.
    save_history_callback = SaveHistoryToCSV(filepath=history_save_path)

    TLogger.info("Callbacks configurados.")
    return [checkpoint_callback, early_stopping_callback, reduce_lr_callback, save_history_callback]

