class DiagnosisEncoder:
    """
    A class to handle the encoding of specific categorical labels related to
    dermatological diagnoses into integer representations based on ISIC conventions.
    """
    def __init__(self):
        """
        Initializes the encoder with predefined mapping dictionaries.
        """
        logger.info("Initializing DiagnosisEncoder with predefined mappings.")

        # --- Define Mappings ---
        # These dictionaries map the string categories to integer values.

        # Mapping for the primary diagnosis (8 classes)
        self.diagnosis_map: Dict[str, int] = {
            "actinic keratosis": 0,
            "basal cell carcinoma": 1,
            "dermatofibroma": 2,
            "melanoma": 3,
            "nevus": 4,
            "pigmented benign keratosis": 5,
            "squamous cell carcinoma": 6,
            "vascular lesion": 7
        }

        # Mapping for the high-level diagnosis (Benign, Malignant, Indeterminate)
        self.diagnosis_1_map: Dict[str, int] = {
            "Benign": 0,
            "Malignant": 1,
            "Indeterminate": 2
        }

        # Mapping for the more detailed diagnosis subgroups (8 classes)
        self.diagnosis_2_map: Dict[str, int] = {
            "Benign epidermal proliferations": 0,
            "Benign melanocytic proliferations": 1,
            "Benign soft tissue proliferations - Fibro-histiocytic": 2,
            "Benign soft tissue proliferations - Vascular": 3,
            "Indeterminate epidermal proliferations": 4,
            "Malignant adnexal epithelial proliferations - Follicular": 5,
            "Malignant epidermal proliferations": 6,
            "Malignant melanocytic proliferations (Melanoma)": 7
        }

        # Binary mapping: Malignant (1) vs. Non-Malignant (0)
        # This is derived from 'diagnosis_1', treating 'Indeterminate' as non-malignant.
        self.benign_malignant_map: Dict[str, int] = {
            "Benign": 0,
            "Malignant": 1,
            "Indeterminate": 0
        }

    def transform(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Applies the predefined mappings to the input DataFrame to create new
        encoded columns.

        Args:
            df (pd.DataFrame): The DataFrame containing the string labels to be encoded.

        Returns:
            pd.DataFrame: A new DataFrame with added columns for the encoded labels.
        """
        if not isinstance(df, pd.DataFrame):
            logger.error("Input must be a pandas DataFrame.")
            raise TypeError("Input must be a pandas DataFrame.")

        logger.info("Starting label encoding transformation.")
        df_encoded = df.copy()

        # --- Apply Mappings ---
        # The .map() method efficiently applies the dictionary mapping.
        # It will produce NaN for any value not found in the dictionary.
        try:
            df_encoded['diagnosis_encoded'] = df_encoded['diagnosis'].map(self.diagnosis_map)
            df_encoded['diagnosis_1_encoded'] = df_encoded['diagnosis_1'].map(self.diagnosis_1_map)
            df_encoded['diagnosis_2_encoded'] = df_encoded['diagnosis_2'].map(self.diagnosis_2_map)
            df_encoded['benign_malignant_encoded'] = df_encoded['diagnosis_1'].map(self.benign_malignant_map)

            # --- Create Melanocytic Flag ---
            # This is a binary flag (1 if 'melanocytic' is in the diagnosis_2 string, 0 otherwise).
            df_encoded['melanocytic_encoded'] = df_encoded['diagnosis_2'].str.contains(
                'melanocytic',
                case=False,
                na=False
            ).astype(int)

        except KeyError as e:
            logger.error(f"A required column is missing from the DataFrame: {e}")
            raise

        # --- Validation and Error Reporting ---
        # Check for any values that failed to map (resulting in NaN).
        encoded_cols = [
            'diagnosis_encoded', 'diagnosis_1_encoded',
            'diagnosis_2_encoded', 'benign_malignant_encoded'
        ]
        for col in encoded_cols:
            if df_encoded[col].isnull().any():
                unmapped_count = df_encoded[col].isnull().sum()
                logger.warning(
                    f"Found {unmapped_count} unmapped values in '{col.replace('_encoded', '')}' column. "
                    "These will be filled with -1 to indicate an unknown category."
                )
                # Fill NaNs and ensure the column is of integer type.
                df_encoded[col] = df_encoded[col].fillna(-1).astype(int)

        logger.info("Label encoding transformation completed successfully.")
        return df_encoded

class DiagnosisDecoder:
    """
    A class to handle the decoding of numerical labels back to their original
    categorical string representations.
    """
    def __init__(self):
        """
        Initializes the decoder with inverted mapping dictionaries.
        """
        logger.info("Initializing DiagnosisDecoder with inverse mappings.")
        encoder = DiagnosisEncoder() # Use an encoder instance to get the maps

        # --- Create Inverse Mappings ---
        # {value: key for key, value in dictionary.items()} is a pythonic way to invert a dictionary.
        self.diagnosis_map_rev: Dict[int, str] = {v: k for k, v in encoder.diagnosis_map.items()}
        self.diagnosis_1_map_rev: Dict[int, str] = {v: k for k, v in encoder.diagnosis_1_map.items()}
        self.diagnosis_2_map_rev: Dict[int, str] = {v: k for k, v in encoder.diagnosis_2_map.items()}

        # Note: The benign_malignant map is not a 1-to-1 mapping, so a simple inversion is ambiguous.
        # We define the reverse map explicitly based on the intended meaning.
        self.benign_malignant_map_rev: Dict[int, str] = {
            0: "Non-Malignant",
            1: "Malignant"
        }
        self.melanocytic_map_rev: Dict[int, str] = {
            0: "Non-Melanocytic",
            1: "Melanocytic"
        }


    def transform(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Applies the inverse mappings to the input DataFrame to create new
        decoded string columns.

        Args:
            df (pd.DataFrame): The DataFrame containing the integer labels to be decoded.

        Returns:
            pd.DataFrame: A new DataFrame with added columns for the decoded string labels.
        """
        if not isinstance(df, pd.DataFrame):
            logger.error("Input must be a pandas DataFrame.")
            raise TypeError("Input must be a pandas DataFrame.")

        logger.info("Starting label decoding transformation.")
        df_decoded = df.copy()

        try:
            df_decoded['diagnosis_decoded'] = df_decoded['diagnosis_encoded'].map(self.diagnosis_map_rev)
            df_decoded['diagnosis_1_decoded'] = df_decoded['diagnosis_1_encoded'].map(self.diagnosis_1_map_rev)
            df_decoded['diagnosis_2_decoded'] = df_decoded['diagnosis_2_encoded'].map(self.diagnosis_2_map_rev)
            df_decoded['benign_malignant_decoded'] = df_decoded['benign_malignant_encoded'].map(self.benign_malignant_map_rev)
            df_decoded['melanocytic_decoded'] = df_decoded['melanocytic_encoded'].map(self.melanocytic_map_rev)
        except KeyError as e:
            logger.error(f"An encoded column is missing from the DataFrame for decoding: {e}")
            raise

        logger.info("Label decoding transformation completed successfully.")
        return df_decoded


