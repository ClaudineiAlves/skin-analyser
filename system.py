class CorrelationIdIntegration:
    def __init__(self):
        """
        Initializes the correlation ID integration using Python's context variables.
        This allows storing and retrieving an ID unique to each execution context (e.g., thread or async task).
        """
        self.correlation_id_var = contextvars.ContextVar("correlation_id", default=None)

    # ---------------------------------------------------------------------------
    # Tools
    # ---------------------------------------------------------------------------
    def generateCorrelationId(self):
        """
        Generates a unique correlation ID based on the current UTC timestamp
        and the current thread identifier.

        This ID can be used to trace a request or process across multiple components or logs.
        Example format: '20250715142530123456-140736745453312'
        """
        now = datetime.utcnow().strftime(
            "%Y%m%d%H%M%S%f"
        )  # Current UTC datetime in microsecond precision
        tid = threading.get_ident()  # Thread identifier
        return f"{now}-{tid}"

    def getCorrelationId(self):
        """
        Retrieves the correlation ID for the current execution context.
        If none exists, a new one is generated and stored.

        This ensures that all logs or actions within the same context share the same identifier.
        """
        cid = self.correlation_id_var.get()
        if cid is None:
            cid = self.generateCorrelationId()
            self.correlation_id_var.set(cid)
        return cid


