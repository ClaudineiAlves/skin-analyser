# --- CUSTOM DATA GENERATOR ---
class CustomDataGenerator(Sequence):
    """
    Generates data for Keras models by loading and processing images from disk in batches.
    This is the key to working with large datasets on limited memory.
    """
    def __init__(self, image_paths, labels, batch_size, img_size, num_classes_map, output_names, input_name):
        self.image_paths = image_paths
        self.labels = labels
        self.batch_size = batch_size
        self.img_size = img_size
        self.num_classes_map = num_classes_map
        self.output_names = output_names
        self.input_name = input_name
        self.n = len(self.image_paths)

    def __len__(self):
        """Denotes the number of batches per epoch."""
        return int(np.ceil(self.n / self.batch_size))

    def __getitem__(self, index):
        """Generate one batch of data."""
        start_idx = index * self.batch_size
        end_idx = min((index + 1) * self.batch_size, self.n)

        batch_paths = self.image_paths[start_idx:end_idx]
        batch_labels_raw = self.labels[start_idx:end_idx]

        # --- Load and process images on-the-fly ---
        batch_images = []
        for path in batch_paths:
            img = Image.open(path)
            img = img.resize((self.img_size, self.img_size))
            if img.mode != 'RGB':
                img = img.convert('RGB')
            batch_images.append(np.array(img))

        # --- Pre-process images ---
        x_batch = np.array(batch_images, dtype=np.float32) / 255.0

        # --- Format labels into a dictionary ---
        y_batch = {
            self.output_names[0]: tf.keras.utils.to_categorical(batch_labels_raw[:, 0], num_classes=self.num_classes_map['diagnosis_output']),
            self.output_names[1]: tf.keras.utils.to_categorical(batch_labels_raw[:, 1], num_classes=self.num_classes_map['diagnosis_1_output']),
            self.output_names[2]: tf.keras.utils.to_categorical(batch_labels_raw[:, 2], num_classes=self.num_classes_map['diagnosis_2_output']),
            self.output_names[3]: batch_labels_raw[:, 3].astype(np.float32),
            self.output_names[4]: batch_labels_raw[:, 4].astype(np.float32)
        }

        # The input (x) must also be a dictionary to match the model's input layer name
        return {self.input_name: x_batch}, y_batch

