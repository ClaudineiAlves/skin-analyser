# Use tqdm for progress bars if available
try:
    from tqdm import tqdm
except ImportError:
    def tqdm(iterable, *args, **kwargs):
        return iterable

class LesionSegmentation:
    """
    Orchestrates a systematic pipeline for lesion segmentation and feature extraction.
    """
    def __init__(self, output_root: str = "./segmentation_results"):
        # --- Logger Setup ---
        self.logger = logging.getLogger(self.__class__.__name__)
        if not self.logger.handlers:
            handler = logging.StreamHandler()
            formatter = logging.Formatter('%(asctime)s - %(name)s - %(levelname)s - %(message)s')
            handler.setFormatter(formatter)
            self.logger.addHandler(handler)
        self.logger.setLevel(logging.INFO)

        # --- Path Configuration ---
        self.output_root = Path(output_root)
        self.registry_path = self.output_root / "segmentation_registry.csv"
        self._ensure_dir(self.output_root)

        # --- State and Registry ---
        self._input_images: List[np.ndarray] = []
        self._input_uids: List[str] = []
        self._input_sids: List[int] = []
        self._registry_df = self._load_registry()

    def _ensure_dir(self, path: Path):
        """Create a directory if it doesn't exist."""
        path.mkdir(parents=True, exist_ok=True)

    def _safe_imwrite(self, path: Path, img: np.ndarray):
        """Safely write an image file, creating parent dirs and handling errors."""
        try:
            # This import is here to avoid a top-level dependency on cv2 in this file
            import cv2
            self._ensure_dir(path.parent)
            cv2.imwrite(str(path), img)
        except Exception as e:
            self.logger.warning(f"Failed to save image to {path}: {e}")

    def _load_registry(self) -> pd.DataFrame:
        """Load the CSV registry or create a new one."""
        if self.registry_path.exists():
            return pd.read_csv(self.registry_path)
        return pd.DataFrame(columns=["artifact_id", "universal_id", "source_image_id", "category", "type", "file_path"])

    def set_data(self, images: List[np.ndarray], universal_ids: List[str], source_image_ids: List[int]):
        """Loads the preprocessed data for the segmentation pipeline."""
        if not all(isinstance(i, np.ndarray) for i in images):
            raise TypeError("All items in 'images' must be NumPy arrays.")
        self.logger.info(f"Setting {len(images)} preprocessed images for segmentation.")
        self._input_images = images
        self._input_uids = universal_ids
        self._input_sids = source_image_ids

    def run(self) -> Dict[str, List[Dict[str, Any]]]:
        """Runs the entire segmentation and feature extraction pipeline."""
        if not self._input_images:
            self.logger.error("No data set. Call set_data() before running.")
            return {}

        self.logger.info("=== Starting Lesion Segmentation Pipeline ===")
        all_results: Dict[str, List] = {"segmentation_masks": [], "roi_images": [], "visualizations": [], "features": []}
        new_registry_entries = []

        for i in tqdm(range(len(self._input_images)), desc="Segmenting Images"):
            img, uid, sid = self._input_images[i], self._input_uids[i], self._input_sids[i]

            try:
                # --- Stage 1: Generate Master Segmentation Mask ---
                mask = SegmentationOps.generate_otsu_mask(img, SEGMENTATION_PARAMS['otsu_blur_ksize'])
                if np.sum(mask) == 0:
                    self.logger.warning(f"Master mask for {uid}_{sid} is empty. Skipping.")
                    continue

                # --- Stage 2 & 3: Generate Artifacts, Extract Features, and Register ---
                base_dir = self.output_root / uid / str(sid)

                # --- Masks
                mask_path = base_dir / "mask.png"
                self._safe_imwrite(mask_path, mask)
                new_registry_entries.append({'artifact_id': f"{uid}_{sid}_mask", 'universal_id': uid, 'source_image_id': sid, 'category': 'Mask', 'type': 'Otsu', 'file_path': str(mask_path)})
                all_results["segmentation_masks"].append({'uid': uid, 'sid': sid, 'mask': mask, 'path': str(mask_path)})

                # --- ROI Images
                roi, roi_mask = SegmentationOps.extract_roi_from_mask(img, mask, SEGMENTATION_PARAMS['roi_padding'])
                if roi is not None and roi_mask is not None:
                    roi_transparent = SegmentationOps.apply_mask_as_alpha(roi, roi_mask)
                    roi_path = base_dir / "roi_transparent.png"
                    self._safe_imwrite(roi_path, roi_transparent)
                    new_registry_entries.append({'artifact_id': f"{uid}_{sid}_roi", 'universal_id': uid, 'source_image_id': sid, 'category': 'ROI', 'type': 'Transparent', 'file_path': str(roi_path)})
                    all_results["roi_images"].append({'uid': uid, 'sid': sid, 'roi': roi_transparent, 'path': str(roi_path)})

                # --- Visualizations
                overlay = SegmentationOps.create_overlay_visualization(img, mask, SEGMENTATION_PARAMS['overlay_color'], SEGMENTATION_PARAMS['overlay_alpha'])
                overlay_path = base_dir / "visualization_overlay.png"
                self._safe_imwrite(overlay_path, overlay)
                new_registry_entries.append({'artifact_id': f"{uid}_{sid}_overlay", 'universal_id': uid, 'source_image_id': sid, 'category': 'Visualization', 'type': 'Overlay', 'file_path': str(overlay_path)})

                contour = SegmentationOps.draw_contour_visualization(img, mask, SEGMENTATION_PARAMS['contour_color'], SEGMENTATION_PARAMS['contour_thickness'])
                contour_path = base_dir / "visualization_contour.png"
                self._safe_imwrite(contour_path, contour)
                new_registry_entries.append({'artifact_id': f"{uid}_{sid}_contour", 'universal_id': uid, 'source_image_id': sid, 'category': 'Visualization', 'type': 'Contour', 'file_path': str(contour_path)})

                all_results["visualizations"].append({'uid': uid, 'sid': sid, 'overlay': overlay, 'contour': contour, 'overlay_path': str(overlay_path), 'contour_path': str(contour_path)})

                # --- Numerical Features
                features = {
                    "shape": SegmentationOps.extract_shape_features(mask),
                    "color": SegmentationOps.extract_color_features(img, mask, SEGMENTATION_PARAMS['features_palette_k']),
                    "texture": SegmentationOps.extract_texture_features(img, mask),
                }
                features_path = base_dir / "features.json"
                with open(features_path, 'w') as f:
                    # A custom default function to handle non-serializable numpy types
                    json.dump(features, f, indent=4, default=lambda o: str(o) if isinstance(o, (np.int64, np.float32, np.float64)) else '<not serializable>')
                new_registry_entries.append({'artifact_id': f"{uid}_{sid}_features", 'universal_id': uid, 'source_image_id': sid, 'category': 'Features', 'type': 'JSON', 'file_path': str(features_path)})
                all_results["features"].append({'uid': uid, 'sid': sid, 'data': features, 'path': str(features_path)})

            except Exception as e:
                self.logger.error(f"CRITICAL FAILURE processing {uid}_{sid}: {e}")
                self.logger.debug(traceback.format_exc())

        # --- Finalize Registry ---
        if new_registry_entries:
            new_df = pd.DataFrame(new_registry_entries)
            self._registry_df = pd.concat([self._registry_df, new_df]).drop_duplicates(subset=['artifact_id'], keep='last').reset_index(drop=True)
            self._registry_df.to_csv(self.registry_path, index=False)
            self.logger.info(f"Registry updated with {len(new_registry_entries)} new entries. Total size: {len(self._registry_df)}")

        self.logger.info("=== Segmentation Pipeline Completed Successfully ===")
        return all_results

