# region Main Pipeline Orchestrator ────────────────────────────────────────────────
class DermatologyPipeline:
    """Orquestra a execução de uma sequência de passos de processamento de dados."""
    def __init__(self, config: PipelineConfig):
        self.config = config
        self.logger = LogIntegration()
        self.steps: List[PipelineStep] = []

    def add_step(self, step: PipelineStep) -> 'DermatologyPipeline':
        """Adiciona um passo de processamento ao pipeline."""
        self.steps.append(step)
        return self

    def run(self, initial_data: Dict[str, pd.DataFrame]):
        self.logger.info("="*60 + "\nINICIANDO PIPELINE DE PROCESSAMENTO DE DADOS\n" + "="*60)
        state = PipelineState(initial_data)

        for step in self.steps:
            try:
                state = step.execute(state)
            except Exception as e:
                self.logger.critical(f"ERRO CRÍTICO no passo {step.step_name}: {e}")
                traceback.print_exc()
                return pd.DataFrame(), [], []

        final_df = self._prepare_final_output(state)

        self.logger.info("="*60 + "\nPIPELINE CONCLUÍDO COM SUCESSO\n" + "="*60)
        return final_df, list(state.images_installed), list(state.images_primary_ids)

    def _prepare_final_output(self, state: PipelineState) -> pd.DataFrame:
        """Une os dataframes finais e alinha com as imagens baixadas."""
        pk = self.config.PRIMARY_KEY
        merged_df = pd.merge(
            state.dataframes['lesions'], state.dataframes['diagnosis'], on=pk, how="inner"
        )
        if not merged_df.empty and state.images_primary_ids.size > 0:
            return merged_df.set_index(pk).reindex(state.images_primary_ids).reset_index()
        return pd.DataFrame()

