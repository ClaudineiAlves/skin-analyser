    gray_img = cv2.cvtColor(_ensure_bgr(img), cv2.COLOR_BGR2GRAY)
    binary_mask = (mask > 127).astype(np.uint8)
    # Avoid division by zero if mask is all 0s or all 1s
    if np.count_nonzero(binary_mask) == 0 or np.count_nonzero(binary_mask) == binary_mask.size:
        return mask
    # The lesion is typically darker than the surrounding skin
    mean_foreground = np.mean(gray_img[binary_mask == 1])
    mean_background = np.mean(gray_img[binary_mask == 0])
    # If the foreground is brighter than the background, it's inverted.
    if mean_foreground > mean_background:
        return (1 - binary_mask) * 255
    return binary_mask * 255

