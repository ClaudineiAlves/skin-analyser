class ConsoleNotifier:
    # Default configuration values
    DefaultSettings: ConsoleConfigDict = {
        "system_name": "System",
        "line_length": 50,
        "border_char_top": "=",
        "border_char_sep": "-",
        "color_enabled": True,
        "alignment": "center",
        "uppercase_title": False,
        "prefix": "",
        "suffix": "",
        "border_color": "cyan",
        "text_color": "white",
        "title_color": "yellow"
    }

    def __init__(self, **kwargs: ConsoleConfigDict):
        '''
            Description:
                Initialize ConsoleNotifier with optional custom configuration.

            Parameters:
                **kwargs (ConsoleConfigDict): Optional config overrides.

            Return:
                None
        '''
        default_cfg = self.DefaultSettings
        self.console = Console()
        self.history = []  # Store log and command history
        self._request_count = 0  # Count API-style requests
    # ==================================================================================
    # Config
    # ==================================================================================
        self._system_name = kwargs.get("system_name", default_cfg["system_name"])
        self._line_length = kwargs.get("line_length", default_cfg["line_length"])
        self._border_char_top = kwargs.get("border_char_top", default_cfg["border_char_top"])
        self._border_char_sep = kwargs.get("border_char_sep", default_cfg["border_char_sep"])
        self._color_enabled = kwargs.get("color_enabled", default_cfg["color_enabled"])
        self._alignment = kwargs.get("alignment", default_cfg["alignment"])
        self._uppercase_title = kwargs.get("uppercase_title", default_cfg["uppercase_title"])
        self._prefix = kwargs.get("prefix", default_cfg["prefix"])
        self._suffix = kwargs.get("suffix", default_cfg["suffix"])
        self._border_color = kwargs.get("border_color", default_cfg["border_color"])
        self._text_color = kwargs.get("text_color", default_cfg["text_color"])
        self._title_color = kwargs.get("title_color", default_cfg["title_color"])

    # ==================================================================================
    # Internal Helpers
    # ==================================================================================
    def _apply_alignment(self, text: str) -> str:
        '''
            Description:
                Apply text alignment based on configuration.

            Parameters:
                text (str): Text to be aligned.

            return:
                str: Aligned text.
        '''
        if self._alignment == "left":
            return text.ljust(self._line_length)
        elif self._alignment == "right":
            return text.rjust(self._line_length)
        return text.center(self._line_length)

    def _chunk_text(self, text: str) -> list[str]:
        return [text[i:i+self._line_length] for i in range(0, len(text), self._line_length)]

    def _format_timestamp(self) -> str:
        return datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    # ==================================================================================
    # Basic Header & Logging
    # ==================================================================================
    def print_header(self, title: str) -> None:
        '''
            Description:
                Print a header with optional title.

            Parameters:
                title (str): Header title.

            return:
                None
        '''
        if self._uppercase_title:
            title = title.upper()
        title_lines = self._chunk_text(title)
        title_text = "\n".join(self._apply_alignment(line) for line in title_lines)

        panel_text = Text()
        panel_text.append(self._apply_alignment(f"{self._prefix}{self._system_name}{self._suffix}") + "\n", style=self._title_color)
        panel_text.append(self._border_char_sep * self._line_length + "\n", style=self._border_color)
        panel_text.append(title_text, style=self._text_color)

        self.console.print(Panel(panel_text, width=self._line_length + 4, border_style=self._border_color))

    def log(self, message: str, level: str = "INFO", context: Optional[str] = None) -> None:
        '''
            Description:
                Log a message with optional context and level.

            Parameters:
                message (str): Message to log.
                level (str): Log level ("DEBUG", "INFO", "SUCCESS", "WARNING", "ERROR").
                context (str): Optional context for the log.

            return:
                None
        '''
        level_colors = {
            "DEBUG": "blue",
            "INFO": "cyan",
            "SUCCESS": "green",
            "WARNING": "yellow",
            "ERROR": "red"
        }
        color = level_colors.get(level.upper(), "white")
        timestamp = self._format_timestamp()
        prefix = f"[{level}]"
        if context:
            prefix += f" [{context}]"

        self.history.append((timestamp, level, context, message))
        text = Text(f"{timestamp} {prefix} {message}", style=color)
        self.console.print(text)

    # ==================================================================================
    # API-Style Logging
    # ==================================================================================
    def log_request(self, method: str, endpoint: str, payload: dict = None, headers: dict = None):
        '''
            Description:
                Display an API-style request block with method, endpoint, headers, and payload.
            Parameters:
                method (str): HTTP method (GET, POST, etc.).
                endpoint (str): API endpoint.
                payload (dict): Request payload.
                headers (dict): Request headers.
            return:
                None
        '''
        self._request_count += 1
        ts = self._format_timestamp()
        title = f"REQ #{self._request_count} {method.upper()} {endpoint}"
        panel_text = Text(f"Time: {ts}\n", style="cyan")

        if headers:
            panel_text.append("\nHeaders:\n", style="magenta")
            panel_text.append(json.dumps(headers, indent=2), style="white")

        if payload:
            panel_text.append("\n\nPayload:\n", style="yellow")
            panel_text.append(json.dumps(payload, indent=2), style="white")

        self.console.print(Panel(panel_text, title=title, border_style="blue"))
        self.history.append((ts, "REQUEST", endpoint, {"method": method, "headers": headers, "payload": payload}))

    def log_response(self, status_code: int, data: dict = None, elapsed: float = None):
        '''
            Description:
                Display an API-style response block with status code, data, and elapsed time.
            Parameters:
                status_code (int): HTTP status code.
                data (dict): Response data.
                elapsed (float): Elapsed time in seconds.
            return:
                None
        '''
        ts = self._format_timestamp()
        color = "green" if 200 <= status_code < 300 else "red" if status_code >= 400 else "yellow"
        status_text = f"{status_code} {'OK' if status_code == 200 else 'ERROR' if status_code >= 400 else 'INFO'}"

        panel_text = Text(f"Time: {ts}\nStatus: {status_text}", style=color)
        if elapsed is not None:
            panel_text.append(f"\nElapsed: {elapsed:.2f}s", style="cyan")

        if data:
            try:
                panel_text.append("\n\nResponse Body:\n", style="yellow")
                panel_text.append(json.dumps(data, indent=2, default=str), style="white")
            except TypeError:
                panel_text.append("\n\n[Non-serializable data]", style="red")

        self.console.print(Panel(panel_text, title="RESPONSE", border_style=color))
        self.history.append((ts, "RESPONSE", status_code, data))

    # ==================================================================================
    # User Interaction
