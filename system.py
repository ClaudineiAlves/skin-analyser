class DatasetSplitter:
    """
    Handles the splitting of datasets (images and labels) into training,
    validation, and test sets, with support for stratification.
    """
    def __init__(self, images: List[np.ndarray], labels_dict: Dict[str, List[Any]], ids: List[str]):
        """
        Initializes the splitter with all necessary data components.

        Args:
            images (List[np.ndarray]): The list of images.
            labels_dict (Dict[str, List[Any]]): A dictionary of label lists from DataOrganizer.
            ids (List[str]): The list of corresponding IDs.
        """
        logger.info("Initializing DatasetSplitter.")
        try:
            num_images = len(images)
            if num_images == 0:
                raise ValueError("Input 'images' list cannot be empty.")
            if len(ids) != num_images:
                raise ValueError(f"Length mismatch: {num_images} images vs. {len(ids)} IDs.")
            for name, labels in labels_dict.items():
                if len(labels) != num_images:
                    raise ValueError(f"Length mismatch for label '{name}': {num_images} images vs. {len(labels)} labels.")

            self.images = np.array(images)
            self.labels_dict = {name: np.array(values) for name, values in labels_dict.items()}
            self.ids = np.array(ids)
            logger.info(f"Loaded {len(self.images)} samples ready for splitting.")

        except ValueError as e:
            logger.error(f"Error during DatasetSplitter initialization: {e}")
            raise

    def split(self, test_size: float = 0.2, val_size: float = 0.15, stratify_on: Optional[str] = 'diagnosis_encoded', random_state: int = 42) -> Dict[str, Dict[str, Any]]:
        """
        Performs a stratified train-validation-test split.

        Args:
            test_size (float): Proportion of the dataset for the test split.
            val_size (float): Proportion of the dataset for the validation split (from the original dataset size).
            stratify_on (Optional[str]): The label key to use for stratification. If None, split is random.
            random_state (int): Seed for the random number generator for reproducibility.

        Returns:
            Dict[str, Dict[str, Any]]: A dictionary containing 'train', 'validation', and 'test' sets.
        """
        num_samples = len(self.images)
        indices = np.arange(num_samples)

        stratify_array = None
        if stratify_on:
            if stratify_on not in self.labels_dict:
                logger.warning(f"Stratification key '{stratify_on}' not found in labels. Performing a random split.")
            else:
                stratify_array = self.labels_dict[stratify_on]
                unique, counts = np.unique(stratify_array, return_counts=True)
                if np.any(counts < 2):
                    logger.warning(f"Some classes in '{stratify_on}' have fewer than 2 members. Stratification is not possible. Performing a random split.")
                    stratify_array = None

        logger.info(f"Performing split: Test Size={test_size}, Val Size={val_size}, Stratify By='{stratify_on or 'None'}'")

        try:
            # First Split: (Train + Val) vs. Test
            train_val_indices, test_indices = train_test_split(
                indices,
                test_size=test_size,
                random_state=random_state,
                stratify=stratify_array
            )

            # Recalculate validation size as a proportion of the remaining data
            relative_val_size = val_size / (1.0 - test_size)
            stratify_train_val = stratify_array[train_val_indices] if stratify_array is not None else None

            # Second Split: Train vs. Val
            train_indices, val_indices = train_test_split(
                train_val_indices,
                test_size=relative_val_size,
                random_state=random_state,
                stratify=stratify_train_val
            )
        except Exception as e:
            logger.error(f"An error occurred during the split process: {e}")
            raise

        def get_subset(selected_indices: np.ndarray) -> Dict[str, Any]:
            if len(selected_indices) == 0: return {'images': [], 'labels': {}, 'ids': []}
            return {
                'images': self.images[selected_indices],
                'labels': {name: values[selected_indices] for name, values in self.labels_dict.items()},
                'ids': self.ids[selected_indices]
            }

        logger.info("Split complete.")
        logger.info(f"  - Training set size: {len(train_indices)}")
        logger.info(f"  - Validation set size: {len(val_indices)}")
        logger.info(f"  - Test set size: {len(test_indices)}")

        return {
            'train': get_subset(train_indices),
            'validation': get_subset(val_indices),
            'test': get_subset(test_indices)
        }

