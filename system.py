    def run(self, resume: bool = True, verbose: bool = False) -> Tuple[List[np.ndarray], List[str], List[int], pd.DataFrame]:
        """Runs the augmentation chains defined in the configuration."""
        if verbose: self.logger.setLevel(logging.DEBUG)
        else: self.logger.setLevel(logging.INFO)

        self.logger.info(f"=== STARTING: Exponential Augmentation Pipeline (Resume={resume}, Verbose={verbose}) ===")
        if not self._input_data:
            self.logger.error("No data set. Call set_data() before running.")
            return [], [], [], pd.DataFrame()

        # --- CORRECTED ID TRACKING ---
        max_id_tracker = {}
        if not self._registry.empty:
            # Ensure 'source_image_id' is numeric before calling .max()
            numeric_sids = pd.to_numeric(self._registry['source_image_id'], errors='coerce')
            max_ids = self._registry.assign(source_image_id=numeric_sids).groupby('universal_id')['source_image_id'].max().dropna().astype(int)
            max_id_tracker = max_ids.to_dict()

        all_final_images_pil: List[Image.Image] = []
        all_final_uids: List[str] = []
        all_final_sids: List[int] = []
        new_registry_rows: List[Dict[str, Any]] = []

        max_var_per_op = self.config.get('max_variations_per_op', None)

        for record in tqdm(self._input_data, desc="Processing source images"):
            img_original_pil, uid, sid = record["image"], record["universal_id"], record["source_image_id"]

            last_id = max_id_tracker.get(uid, sid)
            if last_id < sid:
                last_id = sid

            for chain_name, operations in self.config['chains'].items():
                self.logger.info(f"--- Processing Image (UID: {uid}, SID: {sid}) | Chain: '{chain_name}' ---")

                # The queue now holds tuples of (image_object, parent_id, modification_chain_list, image_id)
                tasks_queue: List[Tuple[Image.Image, str, List[str], int]] = [(img_original_pil, f"original_{uid}_{sid}", [], sid)]

                for op_idx, op_info in enumerate(operations):
                    op_name = op_info['op']
                    self.logger.info(f"  [Step {op_idx + 1}/{len(operations)}] Applying '{op_name}'. Variations in queue: {len(tasks_queue)}")
                    next_step_tasks = list(tasks_queue)

                    for current_img_pil, parent_id, mod_chain, current_sid in tasks_queue:
                        try:
                            aug_func = getattr(AugmentationOps, op_name)
                            params = self.config['default_params'].get(op_name, {})
                            possible_mods = aug_func(current_img_pil, **params)
                            mods_to_process = random.sample(possible_mods, min(len(possible_mods), max_var_per_op)) if max_var_per_op and possible_mods else possible_mods

                            for modified_img_pil, modifiers in mods_to_process:
                                last_id += 1 # Increment for a new unique ID
                                new_mod_chain = mod_chain + [f"{op_name}({json.dumps(modifiers)})"]
                                mod_str = "_".join([f"{k}-{v}" for k, v in modifiers.items()]).replace('.','_').replace(' ','')
                                file_suffix = f"{chain_name}_{op_name}_{mod_str}_{now_utc_str()}.png"
                                path = self.augmentation_root / uid / str(sid) / file_suffix # Folders are based on original sid

                                if safe_imwrite_pil(path, modified_img_pil):
                                    artifact_id, new_row = self._create_artifact_record(uid, last_id, chain_name, parent_id, new_mod_chain, path)
                                    new_registry_rows.append(new_row)
                                    # Add the new unique ID to the task tuple
                                    next_step_tasks.append((modified_img_pil, artifact_id, new_mod_chain, last_id))
                        except Exception:
                            self.logger.error(f"Failed during stage '{op_name}' for {uid}_{sid}: {traceback.format_exc()}")
                            if self.strict_mode: raise

                    tasks_queue = next_step_tasks
                    if not tasks_queue:
                        self.logger.warning("  Task queue became empty, interrupting chain.")
                        break

                # Correctly collect the final unique IDs
                for final_img_pil, _, _, final_sid in tasks_queue:
                    all_final_images_pil.append(final_img_pil)
                    all_final_uids.append(uid)
                    all_final_sids.append(final_sid) # Append the correct, unique ID

            max_id_tracker[uid] = last_id

        if new_registry_rows:
            new_df = pd.DataFrame(new_registry_rows)
            self._registry = pd.concat([self._registry, new_df], ignore_index=True).drop_duplicates(subset=['artifact_id'])
            self._registry.to_csv(self.registry_path, index=False)
            self.logger.info(f"Saved {len(new_registry_rows)} new entries to the registry.")

        final_images_np = [from_pil(img) for img in all_final_images_pil]
        self.logger.info(f"=== COMPLETED: Augmentation pipeline finished. Total images in memory: {len(final_images_np)}. ===")
        return final_images_np, all_final_uids, all_final_sids, self.get_registry_dataframe()

