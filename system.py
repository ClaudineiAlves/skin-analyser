class PipelineStep:
    """Classe base para todos os passos do pipeline."""
    def __init__(self, config: PipelineConfig, logger: LogIntegration):
        self.config = config
        self.logger = logger
        self.step_name = self.__class__.__name__

    def execute(self, state: PipelineState) -> PipelineState:
        self.logger.info(f"--- EXECUTANDO PASSO: {self.step_name} ---")
        start_time = time.time()

        updated_state = self._process(state)

        end_time = time.time()
        self.logger.info(f"--- PASSO {self.step_name} CONCLUÍDO (Duração: {end_time - start_time:.2f}s) ---\n")
        return updated_state

    def _process(self, state: PipelineState) -> PipelineState:
        """Lógica principal do passo a ser implementada pelas subclasses."""
        raise NotImplementedError

class DataProfiler(PipelineStep):
    """Gera um relatório detalhado sobre a qualidade e estatísticas dos dados."""

    def _process(self, state: PipelineState) -> PipelineState:
        if not self.config.ENABLE_PROFILING:
            self.logger.warning("Data Profiling está desativado na configuração.")
            return state

        os.makedirs(self.config.PROFILING_OUTPUT_DIR, exist_ok=True)

        report = f"# Relatório de Vistoria de Dados - {self.stage}\n\n"

        for name, df in state.dataframes.items():
            report += self._profile_dataframe(name, df)

        report_path = os.path.join(self.config.PROFILING_OUTPUT_DIR, f"profiling_report_{self.stage.lower()}.md")
        with open(report_path, 'w', encoding='utf-8') as f:
            f.write(report)
        self.logger.info(f"Relatório de vistoria '{self.stage}' salvo em: {report_path}")

        state.profiling_reports[self.stage] = report
        return state

    def set_stage(self, stage: str):
        self.stage = stage # 'Before' ou 'After'
        return self

    def _profile_dataframe(self, name: str, df: pd.DataFrame) -> str:
        if df.empty:
            return f"## Tabela: `{name}`\n\n- O DataFrame está vazio.\n\n"

        pk = self.config.PRIMARY_KEY

        # Visão Geral
        report_part = f"## Tabela: `{name}`\n\n"
        report_part += f"- **Dimensões:** {df.shape[0]} linhas, {df.shape[1]} colunas.\n"
        report_part += f"- **Linhas Duplicadas:** {df.duplicated().sum()}.\n"

        # Análise de Nulos
        missing_values = df.isnull().sum()
        missing_values = missing_values[missing_values > 0].sort_values(ascending=False)
        if not missing_values.empty:
            report_part += "\n### Análise de Valores Nulos\n"
            report_part += "| Coluna | Contagem de Nulos | Percentual |\n"
            report_part += "|--------|-------------------|------------|\n"
            for col, count in missing_values.items():
                percent = (count / len(df)) * 100
                report_part += f"| `{col}` | {count} | {percent:.2f}% |\n"

        # Análise Categórica
        if name == 'diagnosis':
            report_part += self._profile_categorical(df, 'diagnosis', f"{name}_diagnosis_dist_{self.stage.lower()}.png")
            report_part += self._profile_categorical(df, 'diagnosis_1', f"{name}_diagnosis_1_dist_{self.stage.lower()}.png")

        return report_part + "\n---\n"

    def _profile_categorical(self, df: pd.DataFrame, col: str, filename: str) -> str:
        if col not in df.columns or df[col].isnull().all():
            return ""

        report_part = f"\n### Distribuição de `{col}`\n"
        counts = df[col].value_counts()
        report_part += "| Categoria | Contagem |\n"
        report_part += "|-----------|----------|\n"
        for cat, count in counts.items():
            report_part += f"| {cat} | {count} |\n"

        # Gerar e salvar gráfico
        plt.figure(figsize=(12, 7))
        sns.barplot(x=counts.index, y=counts.values, palette='viridis')
        plt.title(f'Distribuição de {col} ({self.stage})', fontsize=16)
        plt.ylabel('Contagem', fontsize=12)
        plt.xlabel(col, fontsize=12)
        plt.xticks(rotation=45, ha='right')
        plt.tight_layout()
        chart_path = os.path.join(self.config.PROFILING_OUTPUT_DIR, filename)
        plt.savefig(chart_path)
        plt.close()
        report_part += f"\n![Gráfico de Distribuição de {col}]({filename})\n"

        return report_part

class DiagnosisImputer(PipelineStep):
    """Preenche dados de diagnóstico faltantes de forma bidirecional."""
    # ... (a lógica interna de _build_maps e run foi adaptada para o _process) ...
    def _process(self, state: PipelineState) -> PipelineState:
        if not self.config.ENABLE_IMPUTATION:
            self.logger.warning("Imputation está desativado.")
            return state

        self._build_maps()
        df = state.dataframes['diagnosis']

        # Lógica de imputação (adaptada da versão anterior)
        d1_missing = df['diagnosis_1'].isnull()
        d2_missing = df['diagnosis_2'].isnull()

        if d1_missing.any():
            filler_d1 = df['diagnosis'].map(self.diag_to_d1_map)
            df.loc[d1_missing, 'diagnosis_1'] = filler_d1[d1_missing]
        if d2_missing.any():
            filler_d2 = df['diagnosis'].map(self.diag_to_d2_map)
            df.loc[d2_missing, 'diagnosis_2'] = filler_d2[d2_missing]

        diag_missing_mask = df['diagnosis'].isnull()
        if diag_missing_mask.any():
            for col in self.config.DIAGNOSIS_FALLBACK_PRIORITY:
                if col in df.columns:
                    mapped_values = df[col].str.lower().map(self.fallback_to_diag_map)
                    df['diagnosis'].fillna(mapped_values, inplace=True)

        state.dataframes['diagnosis'] = df
        return state

    def _build_maps(self):
        self.diag_to_d1_map = {k: v[0] for k, v in self.config.DIAGNOSIS_RELATION_MAP.items()}
        self.diag_to_d2_map = {k: v[1] for k, v in self.config.DIAGNOSIS_RELATION_MAP.items()}
        self.fallback_to_diag_map = {}
        for diag, (d1, d2) in self.config.DIAGNOSIS_RELATION_MAP.items():
            if d1: self.fallback_to_diag_map[d1.lower()] = diag
            if d2: self.fallback_to_diag_map[d2.lower()] = diag

class FeatureEngineer(PipelineStep):
    """Cria novos atributos (features) a partir dos dados existentes."""
    def _process(self, state: PipelineState) -> PipelineState:
        if not self.config.ENABLE_FEATURE_ENGINEERING:
            self.logger.warning("Engenharia de Atributos está desativada.")
            return state

        df = state.dataframes['diagnosis']

        def map_category(diag2_text):
            if pd.isna(diag2_text): return "Desconhecido"
            text = str(diag2_text).lower()
            if "benign" in text: return "Proliferação Benigna"
            if "malignant" in text: return "Proliferação Maligna"
            if "indeterminate" in text: return "Proliferação Indeterminada"
            return "Outros"

        df['diagnosis_category'] = df['diagnosis_2'].apply(map_category)
        self.logger.info("Nova coluna 'diagnosis_category' criada.")

        state.dataframes['diagnosis'] = df
        return state

class DataValidator(PipelineStep):
    """Valida a integridade dos dados e remove registros inválidos."""
    def _process(self, state: PipelineState) -> PipelineState:
        if not self.config.ENABLE_VALIDATION:
            self.logger.warning("Validação está desativada.")
            return state

        pk = self.config.PRIMARY_KEY
        dfs = state.dataframes

        if dfs['images'].empty:
            self.logger.critical("DataFrame de imagens vazio. Validação abortada.")
            return state

        valid_id_pool = set(dfs['images'][pk].dropna().unique())
        bad_ids = set()

        for name, df in dfs.items():
            required = self.config.REQUIRED_FIELDS.get(name, {})
            for col, is_req in required.items():
                if is_req and col in df.columns and df[col].isnull().any():
                    invalidated_ids = set(df[df[col].isnull()][pk].unique())
                    bad_ids.update(invalidated_ids)

        final_valid_ids = valid_id_pool - bad_ids

        for name, df in dfs.items():
            state.dataframes[name] = df[df[pk].isin(final_valid_ids)].copy()

        state.metrics['bad_ids'] = bad_ids
        self.logger.info(f"{len(bad_ids)} IDs inválidos removidos. {len(final_valid_ids)} IDs válidos restantes.")
        return state

class ImageDownloader(PipelineStep):
    """Baixa e processa as imagens associadas aos IDs válidos."""
    def _process(self, state: PipelineState) -> PipelineState:
        if not self.config.ENABLE_IMAGE_DOWNLOAD:
            self.logger.warning("Download de imagens está desativado.")
            return state

        tools = DataSetTools(self.logger)
        df_images = state.dataframes["images"]
        pk = self.config.PRIMARY_KEY

        for row in df_images.itertuples(index=False):
            uid = getattr(row, pk)
            url = getattr(row, 'public_url')

            result = tools.download_image_with_retries(
                url=url,
                file_path=os.path.join(self.config.DEFAULT_FILE_DIR, "images", str(uid)),
                file_name=str(uid)
            )
            if result.get("success"):
                image_np = tools.normalize_and_resize(result["image_bytes"], self.config.IMAGE_TARGET_SIZE)
                state.images_installed = tools.append_image_to_array(state.images_installed, image_np)
                state.images_primary_ids = np.append(state.images_primary_ids, uid)

        self.logger.info(f"{len(state.images_primary_ids)} imagens baixadas e processadas com sucesso.")
        return state

