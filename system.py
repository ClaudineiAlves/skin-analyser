    def download_image_with_retries(self, url: str, file_path: str, file_name: str, retries: int = 3, delay: int = 5) -> Dict[str, Any]:
        """Tenta baixar uma imagem com um número configurável de retentativas."""
        for attempt in range(retries):
            try:
                os.makedirs(file_path, exist_ok=True)
                headers = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/91.0.4472.124 Safari/537.36'}
                response = requests.get(url, timeout=20, headers=headers)
                response.raise_for_status()
                img = Image.open(BytesIO(response.content))

                full_path = os.path.join(file_path, f"{file_name}.jpg")
                if img.mode in ("RGBA", "P"):
                    img = img.convert("RGB")

                img.save(full_path, "JPEG")
                self.logger.info(f"Sucesso no download de {url} para {full_path}")
                return {"success": True, "file_full_path": full_path, "image_bytes": response.content}

            except requests.exceptions.RequestException as e:
                self.logger.warning(f"Falha ao baixar {url} (tentativa {attempt + 1}/{retries}): {e}")
                if attempt < retries - 1:
                    self.logger.info(f"Aguardando {delay} segundos antes de tentar novamente...")
                    time.sleep(delay)
                else:
                    self.logger.error(f"Falha final ao baixar {url} após {retries} tentativas.")
                    return {"success": False, "error": str(e)}
        return {"success": False, "error": "Número máximo de retentativas atingido."}


    def normalize_and_resize(self, image_bytes: bytes, target_size: Tuple[int, int]) -> np.ndarray:
        img = Image.open(BytesIO(image_bytes)).convert("RGB").resize(target_size)
        return np.array(img)

    def append_image_to_array(self, image_array: np.ndarray, new_image: np.ndarray) -> np.ndarray:
        if image_array.ndim != 4 or new_image.ndim != 3:
            raise ValueError("Dimensões de array inválidas para append. Esperado (N, H, W, C) e (H, W, C).")
        return np.vstack([image_array, np.expand_dims(new_image, axis=0)])
