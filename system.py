class SegmentationOps:
    """A static class containing all segmentation-related image processing methods."""

    @staticmethod
    def generate_otsu_mask(img: np.ndarray, blur_ksize: int) -> np.ndarray:
        """Generates a binary mask using Otsu's thresholding with post-processing."""
        gray = cv2.cvtColor(_ensure_bgr(img), cv2.COLOR_BGR2GRAY)
        blur = cv2.GaussianBlur(gray, (blur_ksize, blur_ksize), 0)
        _, mask = cv2.threshold(blur, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)

        oriented_mask = _ensure_mask_polarity(mask, img)
        final_mask = _get_largest_component_mask(oriented_mask)
        return final_mask

    @staticmethod
    def extract_roi_from_mask(img: np.ndarray, mask: np.ndarray, padding: int) -> Tuple[Optional[np.ndarray], Optional[np.ndarray]]:
        """Extracts the Region of Interest (ROI) and its corresponding mask."""
        contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        if not contours: return None, None

        main_contour = max(contours, key=cv2.contourArea)
        x, y, w, h = cv2.boundingRect(main_contour)

        # Apply padding
        x_start, y_start = max(0, x - padding), max(0, y - padding)
        x_end, y_end = min(img.shape[1], x + w + padding), min(img.shape[0], y + h + padding)

        return img[y_start:y_end, x_start:x_end], mask[y_start:y_end, x_start:x_end]

    @staticmethod
    def apply_mask_as_alpha(img: np.ndarray, mask: np.ndarray) -> np.ndarray:
        """Applies a mask to an image, making the background transparent (BGRA)."""
        bgr = _ensure_bgr(img)
        # Ensure mask and image have the same dimensions for merging
        if bgr.shape[:2] != mask.shape[:2]:
            mask = cv2.resize(mask, (bgr.shape[1], bgr.shape[0]), interpolation=cv2.INTER_NEAREST)

        b, g, r = cv2.split(bgr)
        alpha = (mask > 127).astype(np.uint8) * 255
        return cv2.merge([b, g, r, alpha])

    @staticmethod
    def create_overlay_visualization(img: np.ndarray, mask: np.ndarray, color: Tuple[int, int, int], alpha: float) -> np.ndarray:
        """Creates a colored overlay of the mask on the original image."""
        img_bgr = _ensure_bgr(img)
        overlay = img_bgr.copy()
        overlay[mask > 127] = color
        return cv2.addWeighted(overlay, alpha, img_bgr, 1 - alpha, 0)

    @staticmethod
    def draw_contour_visualization(img: np.ndarray, mask: np.ndarray, color: Tuple[int, int, int], thickness: int) -> np.ndarray:
        """Draws the main contour of the mask on the image."""
        img_bgr = _ensure_bgr(img)
        contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        if not contours: return img_bgr

        main_contour = max(contours, key=cv2.contourArea)
        return cv2.drawContours(img_bgr.copy(), [main_contour], -1, color, thickness)

    @staticmethod
    def extract_shape_features(mask: np.ndarray) -> Dict[str, Optional[float]]:
        """Calculates classic clinical (ABCD) and other shape features from the mask."""
        if np.sum(mask) == 0: return {}
        contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        if not contours: return {}

        cnt = max(contours, key=cv2.contourArea)
        area = float(cv2.contourArea(cnt))
        perimeter = float(cv2.arcLength(cnt, True))
        x, y, w, h = cv2.boundingRect(cnt)

        # Asymmetry: Compare mask with its vertical flip
        flipped_mask = cv2.flip(mask, 1) # Horizontal flip
        xor_mask = cv2.bitwise_xor(mask, flipped_mask)
        asymmetry_score = np.sum(xor_mask > 0) / (2.0 * area + 1e-9)

        # Circularity & Border Irregularity
        circularity = (4.0 * math.pi * area / (perimeter**2)) if perimeter > 0 else 0.0
        border_irregularity = 1.0 - circularity

        # Convex Hull and Solidity
        hull = cv2.convexHull(cnt)
        hull_area = cv2.contourArea(hull)
        solidity = area / (hull_area + 1e-9)

        return {
            'asymmetry_score': asymmetry_score,
            'border_irregularity': border_irregularity,
            'diameter_pixels': float(max(w, h)),
            'area_pixels': area,
            'perimeter_pixels': perimeter,
            'circularity': circularity,
            'solidity': solidity,
        }

    @staticmethod
    def extract_color_features(img: np.ndarray, mask: np.ndarray, k: int) -> Dict[str, Any]:
        """Extracts a comprehensive set of color features from the masked region."""
        if not SKLEARN_AVAILABLE: return {"error": "scikit-learn not available"}

        img_bgr, mask_bin = _ensure_bgr(img), (mask > 127)
        pixels = img_bgr[mask_bin]
        if pixels.shape[0] < k: return {"error": f"not enough pixels in mask for KMeans (found {pixels.shape[0]}, need {k})"}

        # KMeans for color palette
        kmeans = KMeans(n_clusters=k, n_init='auto', random_state=42).fit(pixels)
        palette_bgr = [c.tolist() for c in kmeans.cluster_centers_.astype(np.uint8)]
        proportions = [float(np.sum(kmeans.labels_ == i)) / len(kmeans.labels_) for i in range(k)]

        # Color moments in LAB space
        lab_img = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2LAB)
        l_channel, a_channel, b_channel = cv2.split(lab_img)
        l_mean, l_std = cv2.meanStdDev(l_channel, mask=mask)
        a_mean, a_std = cv2.meanStdDev(a_channel, mask=mask)
        b_mean, b_std = cv2.meanStdDev(b_channel, mask=mask)

        return {
            "dominant_colors_bgr": palette_bgr,
            "color_proportions": proportions,
            "lab_moments": {
                'l_mean': l_mean[0][0], 'l_std': l_std[0][0],
                'a_mean': a_mean[0][0], 'a_std': a_std[0][0],
                'b_mean': b_mean[0][0], 'b_std': b_std[0][0],
            }
        }

    @staticmethod
    def extract_texture_features(img: np.ndarray, mask: np.ndarray) -> Dict[str, Any]:
        """Extracts texture features using Gray-Level Co-occurrence Matrix (GLCM)."""
        if not SKLEARN_AVAILABLE: return {"error": "scikit-image not available for GLCM"}

        gray = cv2.cvtColor(_ensure_bgr(img), cv2.COLOR_BGR2GRAY)
        if np.sum(mask) == 0: return {}

        # GLCM requires integer type image
        gray_int = (gray).astype(np.uint8)

        # Calculate GLCM on the masked region
        glcm = graycomatrix(gray_int, distances=[1, 3, 5], angles=[0, np.pi/4, np.pi/2, 3*np.pi/4], levels=256, symmetric=True, normed=True)

        # Mask invalid values (e.g., from empty regions)
        glcm = np.nan_to_num(glcm)

        features = {}
        props = ['contrast', 'dissimilarity', 'homogeneity', 'energy', 'correlation', 'ASM']
        for p in props:
            try:
                features[p] = float(np.mean(graycoprops(glcm, p)))
            except Exception:
                features[p] = None # Handle cases where a property might fail

        return features
