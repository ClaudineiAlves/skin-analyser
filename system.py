def parse_image_and_labels(caminho_img, labels):
    """Carrega e processa uma imagem e seus labels, retornando uma tupla plana de tensores."""
    img = tf.io.read_file(caminho_img)
    img = tf.io.decode_jpeg(img, channels=3)
    img = tf.image.resize(img, [IMG_SIZE, IMG_SIZE])
    img = img / 255.0

    # Retorna uma tupla plana para facilitar a inferência de tipo do TensorFlow
    diag_output = tf.one_hot(tf.cast(labels[0], tf.int32), depth=NUM_CLASSES_MAP['diagnosis_output'])
    diag1_output = tf.one_hot(tf.cast(labels[1], tf.int32), depth=NUM_CLASSES_MAP['diagnosis_1_output'])
    diag2_output = tf.one_hot(tf.cast(labels[2], tf.int32), depth=NUM_CLASSES_MAP['diagnosis_2_output'])
    benign_malignant_output = tf.expand_dims(tf.cast(labels[3], tf.float32), axis=-1)
    melanocytic_output = tf.expand_dims(tf.cast(labels[4], tf.float32), axis=-1)

    return (img, diag_output, diag1_output, diag2_output, benign_malignant_output, melanocytic_output)

def create_dataset(paths, labels):
    """Cria um objeto tf.data.Dataset otimizado para o treinamento."""
    dataset = tf.data.Dataset.from_tensor_slices((paths, labels.astype(np.int32)))

    # 1. Mapeia para carregar e processar os dados numa tupla plana.
    dataset = dataset.map(parse_image_and_labels, num_parallel_calls=tf.data.AUTOTUNE)

    # 2. Mapeia a tupla para a estrutura de dicionário final ANTES de agrupar em lotes.
    #    Isso torna a estrutura do dataset mais explícita para o Keras antes do treinamento.
    def format_to_dict(img, diag, diag1, diag2, bm, mel):
        return (
            {'image_input': img},
            {
                'diagnosis_output': diag,
                'diagnosis_1_output': diag1,
                'diagnosis_2_output': diag2,
                'benign_malignant_output': bm,
                'melanocytic_output': mel
            }
        )
    dataset = dataset.map(format_to_dict, num_parallel_calls=tf.data.AUTOTUNE)

    # 3. Agora embaralha, agrupa em lotes e pré-busca.
    SHUFFLE_BUFFER_SIZE = min(len(paths), 2048)
    dataset = dataset.shuffle(buffer_size=SHUFFLE_BUFFER_SIZE)
    dataset = dataset.batch(BATCH_SIZE)
    dataset = dataset.prefetch(buffer_size=tf.data.AUTOTUNE)
    return dataset


