def _ensure_bgr(img: np.ndarray) -> np.ndarray:
    """Ensure the image is in BGR format."""
    if img.ndim == 2: return cv2.cvtColor(img, cv2.COLOR_GRAY2BGR)
    if img.shape[2] == 4: return cv2.cvtColor(img, cv2.COLOR_BGRA2BGR)
