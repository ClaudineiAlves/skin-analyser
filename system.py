    def _prefix_filter(self):
        """Coment:"""
        parent = self

        class PrefixFilter(logging.Filter):
            def filter(self, record):
                cfg = parent.config.__dict__.get(
                    record.levelname.capitalize()
                ) or parent.config._custom.get(record.levelname)
                record.prefix = cfg.prefix if cfg else ""
                record.log_color = cfg.color if cfg else ""
                return cfg.enabled if cfg else True

        return PrefixFilter()

    def _build_logger(self):
        """
        Builds the logger with appropriate handlers based on configuration.
        """
        # ---------------------------------------------------------------------------
        # Set
        # ---------------------------------------------------------------------------
        try:
            logFileName = self._log_file_name
            logFilePath = self._log_file_path
            if not logFileName.endswith(".log"):
                logFilePath += ".log"
            logFilePath = self._log_file_path
            logFullPath = os.path.join(logFilePath, logFileName)
            logDir = os.path.dirname(logFullPath)
            if not os.path.exists(logDir):
                os.makedirs(logDir, exist_ok=True)

            self._logger = logging.getLogger(self._log_file_name)
            self._logger.handlers.clear()
            log_level_value = logging.getLevelName(self._min_level.upper())

            # Verify if log level is valid
            if isinstance(log_level_value, int):
                self._logger.setLevel(log_level_value)
            else:
                print(f"Invalid log level: {self._min_level}")
                self._logger.setLevel(log_level_value)
            # ---------------------------------------------------------------------------
            # Prefix filter (for console and file)
            # ---------------------------------------------------------------------------
            prefix_filter = self._prefix_filter()
            # ---------------------------------------------------------------------------
            # Console Config
            # ---------------------------------------------------------------------------
            if self._toggle_log_console:
                console_fmt = self._log_console_format
                colors = self._log_colors or {}
                console = colorlog.StreamHandler()
                console.addFilter(prefix_filter)
                formatter = colorlog.ColoredFormatter(
                    console_fmt, datefmt=self._log_date_format, log_colors=colors
                )
                console.setFormatter(formatter)
                self._logger.addHandler(console)
            # ---------------------------------------------------------------------------
            # File
            # ---------------------------------------------------------------------------
            # Unified Log Config
            if self._log_unified_file:
                # Unified log configuration: all log levels will be written into a single file

                fh = logging.FileHandler(logFullPath, mode="a")  # Append mode
                # Set the log format for the file handler
                fh.setFormatter(
                    logging.Formatter(
                        self._log_file_format, datefmt=self._log_date_format
                    )
                )
                # Add a filter to include dynamic prefix information (e.g., [INFO], [ERROR])
                fh.addFilter(prefix_filter)
                # Register the handler to the main logger
                self._logger.addHandler(fh)

            else:
                # Separate log configuration: one file per log level

                # Define standard log levels and their corresponding numeric values
                predefined_levels = {
                    "DEBUG": logging.DEBUG,
                    "INFO": logging.INFO,
                    "WARNING": logging.WARNING,
                    "ERROR": logging.ERROR,
                    "CRITICAL": logging.CRITICAL,
                }

                # Create individual handlers for each standard level
                for level_name, level_value in predefined_levels.items():
                    # Retrieve the custom file name if defined, else fallback to lowercase level name

                    logFileName = self._log_files_name_custom.get(
                        level_name, f"{level_name.lower()}"
                    )
                    logFullPath = os.path.join(logFilePath, logFileName)
                    logDir = os.path.dirname(logFullPath)
                    if not os.path.exists(logDir):
                        os.makedirs(logDir, exist_ok=True)

                    # Create the file handler for this specific level
                    handler = logging.FileHandler(logFullPath, mode="a")  # Append mode
                    # Restrict the handler to log only the specific level
                    handler.setLevel(level_value)
                    handler.addFilter(LevelFilter(level_value))
                    # Set the log format and date format for this handler
                    handler.setFormatter(
                        logging.Formatter(
                            self._log_file_format, datefmt=self._log_date_format
                        )
                    )
                    # Add prefix injection filter to enrich log messages
                    handler.addFilter(prefix_filter)
                    # Add the configured handler to the logger
                    self._logger.addHandler(handler)

                # Handle user-defined custom log levels (outside standard DEBUG-CRITICAL)
                for level_name, config in self.config._custom.items():
                    # Convert the level name to its numeric logging level
                    level_value = logging._nameToLevel.get(level_name)

                    # Skip if the level name is invalid
                    if level_value is None:
                        continue
                    # Retrieve the custom file name assigned to this custom level

                    logFileName = (
                        config.fileName
                        if config.fileName != None
                        else f"{level_name.lower()}.log"
                    )
                    logFullPath = os.path.join(logFilePath, logFileName)
                    logDir = os.path.dirname(logFullPath)
                    if not os.path.exists(logDir):
                        os.makedirs(logDir, exist_ok=True)

                    # Create the file handler
                    handler = logging.FileHandler(logFullPath, mode="a")  # Append mode
                    # Limit the handler to only log the specific custom level
                    handler.setLevel(level_value)
                    handler.addFilter(LevelFilter(level_value))
                    # Apply formatting and prefix filter
                    handler.setFormatter(
                        logging.Formatter(
                            self._log_file_format, datefmt=self._log_date_format
                        )
                    )
                    handler.addFilter(prefix_filter)
                    # Add this handler to the logger
                    self._logger.addHandler(handler)

            self._logger.disabled = not self._toggle_log
        except Exception as e:
            raise e

    def _log_with_level(self, level, message, tags=None):
        """Coment:"""

        if isinstance(tags, dict):
            tagsStr = ";".join(f"{k}={v}" for k, v in tags.items())
        elif isinstance(tags, list):
            tagsStr = ";".join(tags)
        else:
            tagsStr = None

        correlationId = self._cid.getCorrelationId()

        levelName = level if isinstance(level, str) else logging.getLevelName(level)

        self._logger.log(level, message, extra={"prefix": ""})

        if self._db_enable and self._logdbIntegration:

            timesTamp = datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S.%f")

            self._logdbIntegration.insert(
                timesTamp, levelName, message, tagsStr, correlationId
            )

    def _remove_console_from_logger(self):
        """Coment:"""
        self._logger = logging.getLogger(self._log_file_name)

        for handler in self._logger.handlers[:]:
            if isinstance(handler, logging.StreamHandler):
                self._logger.removeHandler(handler)

