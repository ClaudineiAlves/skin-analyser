"""
Orchestrator for the Advanced Lesion Segmentation Pipeline.

This script defines the LesionSegmentation class, which takes preprocessed
images as input and performs segmentation, feature extraction, and artifact
generation, maintaining a persistent registry of all outputs.
"""
import logging
import traceback
import pandas as pd
import numpy as np
import json
from pathlib import Path
